package com.donglan.chrona;

import android.content.Context;
import com.donglan.chrona.data.EventCategory;
import com.donglan.chrona.sync.SyncState;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ConcurrentModificationException;
import java.util.List;
import org.json.JSONArray;
import org.json.JSONObject;

/** Browser actions use the same coordinator and explicit calendar confirmation as native settings. */
final class LanSyncApi {
    private static final int PAGE_SIZE = 20;

    static JSONObject read(Context context, int page) throws Exception {
        if (page < 0 || page > 100000) throw new IllegalArgumentException();
        synchronized (AndroidSync.LOCK) {
            WebDavSettingsStore settings = new WebDavSettingsStore(context);
            List<AndroidSync.Pending> pending = AndroidSync.pending(context);
            JSONArray rows = new JSONArray();
            int begin = Math.min(page * PAGE_SIZE, pending.size());
            int end = Math.min(begin + PAGE_SIZE, pending.size());
            for (AndroidSync.Pending item : pending.subList(begin, end)) {
                JSONArray versions = new JSONArray();
                for (int i = 0; i < item.versions.size(); i++) versions.put(new JSONObject()
                        .put("index", i).put("deleted", item.versions.get(i).deleted)
                        .put("description", describe(item.versions.get(i))));
                rows.put(new JSONObject().put("id", item.id).put("signature", item.signature)
                        .put("title", item.title).put("calendar", item.calendar).put("versions", versions));
            }
            return new JSONObject().put("configured", settings.configured())
                    .put("running", AndroidSync.running()).put("status", settings.status())
                    .put("automatic", settings.automatic()).put("pending", rows)
                    .put("page", page).put("hasMore", end < pending.size());
        }
    }

    private static String describe(SyncState.Version version) throws Exception {
        if (version.deleted) return "已删除";
        JSONObject payload = version.payload;
        if ("term".equals(payload.getString("kind")))
            return "类型：课表\n学期编号：" + payload.getInt("index")
                    + "\n课表内容：\n" + payload.getJSONObject("document").toString(2);
        StringBuilder result = new StringBuilder();
        line(result, "记录状态", payload.getString("status"));
        line(result, "来源", payload.getString("source"));
        line(result, "创建时间", time(payload, "createdAt", ZoneOffset.UTC, false));
        JSONArray candidates = payload.getJSONArray("candidates");
        for (int i = 0; i < candidates.length(); i++) {
            JSONObject candidate = candidates.getJSONObject(i);
            ZoneId zone = ZoneId.of(candidate.getString("zone"));
            boolean allDay = candidate.getBoolean("allDay");
            result.append('\n').append(candidate.getBoolean("record") ? "记录" : EventCategory.label(candidate.getString("category")))
                    .append(' ').append(i + 1).append('\n');
            line(result, "标题", candidate.getString("title"));
            line(result, "类型", candidate.getBoolean("record") ? "记录" : EventCategory.label(candidate.getString("category")));
            line(result, "开始", time(candidate, "startAt", zone, allDay));
            line(result, "结束", time(candidate, "endAt", zone, allDay));
            line(result, "截止", time(candidate, "dueAt", zone, false));
            line(result, "时区", zone.getId());
            line(result, "全天", allDay ? "是" : "否");
            line(result, "地点", candidate.getString("location"));
            line(result, "备注", candidate.getString("description"));
            boolean task = !candidate.getBoolean("record") && EventCategory.isTaskLike(candidate.getString("category"));
            line(result, "完成", !task ? "不适用" : candidate.isNull("completedAt") ? "未完成"
                    : "已完成 · " + time(candidate, "completedAt", zone, false));
            line(result, "提醒", "设备本地设置");
            line(result, "自动生成结束时间", candidate.getBoolean("endAutoGenerated") ? "是" : "否");
            line(result, "确认级别", candidate.getInt("uncertainty"));
            line(result, "日程标识", candidate.getString("id"));
        }
        line(result, "附件", payload.getJSONArray("attachments").toString(2));
        line(result, "链接", payload.getString("linkText"));
        line(result, "原文", payload.getString("rawText"));
        return result.toString();
    }

    private static void line(StringBuilder result, String label, Object value) {
        result.append(label).append('：').append(value).append('\n');
    }

    private static String time(JSONObject value, String key, ZoneId zone, boolean allDay) throws Exception {
        if (value.isNull(key)) return "未设置";
        Instant instant = Instant.ofEpochMilli(value.getLong(key));
        return allDay ? instant.atZone(ZoneOffset.UTC).toLocalDate().toString()
                : DateTimeFormatter.ISO_OFFSET_DATE_TIME.format(instant.atZone(zone));
    }

    static JSONObject run(Context context) throws Exception {
        synchronized (AndroidSync.LOCK) {
            if (!new WebDavSettingsStore(context).configured())
                throw new IllegalArgumentException("请先在手机配置 WebDAV");
            if (!AndroidSync.request(context, null)) throw new ConcurrentModificationException();
        }
        return new JSONObject().put("started", true);
    }

    static JSONObject preferences(Context context, JSONObject body) throws Exception {
        if (body.length() != 1 || !(body.opt("automatic") instanceof Boolean))
            throw new IllegalArgumentException();
        boolean automatic = body.getBoolean("automatic");
        synchronized (AndroidSync.LOCK) {
            WebDavSettingsStore settings = new WebDavSettingsStore(context);
            if (automatic && !settings.configured())
                throw new IllegalArgumentException("请先在手机配置 WebDAV");
            settings.automatic(automatic);
            SyncJobService.schedule(context);
        }
        return new JSONObject().put("automatic", automatic);
    }

    static JSONObject resolve(Context context, JSONObject body) throws Exception {
        Object rawIndex = body.get("index"), rawRemove = body.get("removeCalendar");
        if (!(body.get("id") instanceof String) || !(body.get("signature") instanceof String)
                || !(rawIndex instanceof Integer) || !(rawRemove instanceof Boolean))
            throw new IllegalArgumentException();
        int index = (Integer) rawIndex;
        boolean removeCalendar = (Boolean) rawRemove;
        synchronized (AndroidSync.LOCK) {
            AndroidSync.Pending selected = null;
            for (AndroidSync.Pending item : AndroidSync.pending(context))
                if (item.id.equals(body.getString("id"))) { selected = item; break; }
            if (selected == null || !selected.signature.equals(body.getString("signature")))
                throw new ConcurrentModificationException();
            if (index < -1 || index >= selected.versions.size()
                    || selected.calendar && index >= 0 && !removeCalendar)
                throw new IllegalArgumentException();
            if (!AndroidSync.resolve(context, selected, index, removeCalendar, null))
                throw new ConcurrentModificationException();
        }
        return new JSONObject().put("started", true);
    }

    private LanSyncApi() { }
}
