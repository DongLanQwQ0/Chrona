package com.donglan.chrona.data;

/** A proposed calendar entry. Nullable times and reminder mean the AI has not resolved them. */
public final class EventCandidate {
    public static final int CERTAIN = 0, INFERRED = 1, DOUBTFUL = 2;
    public final long id;
    public final long taskId;
    public final String title;
    public final Long startAtMillis;
    public final Long endAtMillis;
    public final String timeZoneId;
    public final String location;
    public final String description;
    public final Integer reminderMinutesBefore;
    public final boolean needsConfirmation;
    public final int uncertaintyLevel;
    public final Long calendarEventId;
    public final String category;
    public final boolean allDay;
    /** True only when the program supplied the default end, never inferred from interval length. */
    public final boolean endAutoGenerated;
    /** A record belongs to the inbox, not the calendar. */
    public final boolean isRecord;
    public final Long dueAtMillis;
    public final Long completedAtMillis;

    public EventCandidate(long id, long taskId, String title, Long startAtMillis,
            Long endAtMillis, String timeZoneId, String location, String description,
            Integer reminderMinutesBefore, boolean needsConfirmation) {
        this(id, taskId, title, startAtMillis, endAtMillis, timeZoneId, location,
                description, reminderMinutesBefore, needsConfirmation, null, EventCategory.EVENT,
                false);
    }

    public EventCandidate(long id, long taskId, String title, Long startAtMillis,
            Long endAtMillis, String timeZoneId, String location, String description,
            Integer reminderMinutesBefore, boolean needsConfirmation, Long calendarEventId) {
        this(id, taskId, title, startAtMillis, endAtMillis, timeZoneId, location,
                description, reminderMinutesBefore, needsConfirmation, calendarEventId,
                EventCategory.EVENT, false);
    }

    public EventCandidate(long id, long taskId, String title, Long startAtMillis,
            Long endAtMillis, String timeZoneId, String location, String description,
            Integer reminderMinutesBefore, boolean needsConfirmation, Long calendarEventId,
            String category, boolean allDay) {
        this(id, taskId, title, startAtMillis, endAtMillis, timeZoneId, location, description,
                reminderMinutesBefore, needsConfirmation, calendarEventId, category, allDay, false);
    }

    public EventCandidate(long id, long taskId, String title, Long startAtMillis,
            Long endAtMillis, String timeZoneId, String location, String description,
            Integer reminderMinutesBefore, boolean needsConfirmation, Long calendarEventId,
            String category, boolean allDay, boolean endAutoGenerated) {
        this(id, taskId, title, startAtMillis, endAtMillis, timeZoneId, location, description,
                reminderMinutesBefore, needsConfirmation, calendarEventId, category, allDay,
                endAutoGenerated, needsConfirmation ? DOUBTFUL : CERTAIN);
    }

    public EventCandidate(long id, long taskId, String title, Long startAtMillis,
            Long endAtMillis, String timeZoneId, String location, String description,
            Integer reminderMinutesBefore, boolean needsConfirmation, Long calendarEventId,
            String category, boolean allDay, boolean endAutoGenerated, int uncertaintyLevel) {
        this(id, taskId, title, startAtMillis, endAtMillis, timeZoneId, location, description,
                reminderMinutesBefore, needsConfirmation, calendarEventId, category, allDay,
                endAutoGenerated, uncertaintyLevel, null, null, false);
    }
    public EventCandidate(long id, long taskId, String title, Long startAtMillis,
            Long endAtMillis, String timeZoneId, String location, String description,
            Integer reminderMinutesBefore, boolean needsConfirmation, Long calendarEventId,
            String category, boolean allDay, boolean endAutoGenerated, int uncertaintyLevel,
            Long dueAtMillis, Long completedAtMillis, boolean isRecord) {
        this.id = id;
        this.taskId = taskId;
        this.title = title;
        this.startAtMillis = startAtMillis;
        this.endAtMillis = endAtMillis;
        this.timeZoneId = timeZoneId;
        this.location = location;
        this.description = description;
        this.reminderMinutesBefore = reminderMinutesBefore;
        this.needsConfirmation = needsConfirmation;
        this.uncertaintyLevel = uncertaintyLevel >= CERTAIN && uncertaintyLevel <= DOUBTFUL
                ? uncertaintyLevel : DOUBTFUL;
        this.calendarEventId = calendarEventId;
        this.category = EventCategory.normalize(category);
        this.allDay = allDay;
        this.endAutoGenerated = endAutoGenerated;
        this.dueAtMillis = dueAtMillis;
        this.completedAtMillis = completedAtMillis;
        this.isRecord = isRecord;
    }
    public boolean isTask() { return !isRecord && EventCategory.isTaskLike(category); }
    public boolean isHomework() { return !isRecord && EventCategory.HOMEWORK.equals(category); }
    public String itemLabel() { return isHomework() ? "作业" : "日程"; }
    public boolean completed() { return isTask() && completedAtMillis != null; }
    public Long anchor() { return startAtMillis != null ? startAtMillis : dueAtMillis; }
    /** Derived deadline; never replaces an explicit (including absent) source deadline. */
    public Long effectiveDueAtMillis() {
        return !isTask() ? null : dueAtMillis != null ? dueAtMillis
                : endAtMillis != null ? endAtMillis : startAtMillis;
    }
    public Long reminderAnchor() { return isTask() ? effectiveDueAtMillis() : anchor(); }
    public boolean point() { return isTask() && (startAtMillis == null || endAtMillis == null); }
    public Long calendarStart() { return isRecord ? null : anchor(); }
    public Long calendarEnd() {
        Long begin = calendarStart();
        return begin == null ? null : endAtMillis != null && endAtMillis > begin ? endAtMillis : begin + 60_000L;
    }
    public String taskState(long now) {
        if (completed()) return "已完成";
        Long due = effectiveDueAtMillis();
        return due != null && due < now ? "已逾期" : "待完成";
    }
    public boolean settled() {
        return isRecord || completed() || (!needsConfirmation && (isTask() || calendarEventId != null));
    }
}
