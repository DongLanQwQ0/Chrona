/** Portable content only: credentials, calendar IDs, reminder settings and paths never cross devices. */
public final class TaskCodec {
    public static final long MAX_ATTACHMENT_BYTES = 20L * 1024 * 1024;
    public static final int MAX_TASK_BYTES = 16 * 1024 * 1024;
    public static final int MAX_CANDIDATES = 30_000;
    private static final long MIN_TIME = -62_135_596_800_000L, MAX_TIME = 253_402_300_799_999L;

    private TaskCodec() { }

    public static JSONObject candidate(EventCandidate value) throws IOException {
        try {
            return new JSONObject().put("id", UUID.randomUUID().toString())
                    .put("title", value.title).put("startAt", nullable(value.startAtMillis))
                    .put("endAt", nullable(value.endAtMillis)).put("zone", text(value.timeZoneId, "UTC"))
                    .put("location", text(value.location, "")).put("description", text(value.description, ""))
                    .put("category", value.category).put("allDay", value.allDay)
                    .put("dueAt",nullable(value.dueAtMillis)).put("completedAt",nullable(value.completedAtMillis)).put("record",value.isRecord)
                    .put("recurrence", value.repeatRule == null ? JSONObject.NULL : value.repeatRule.toJson())
                    .put("repeatExceptions", portableOccurrenceUpdate(new JSONObject(value.repeatExceptions)))
                    .put("repeatStoppedAt", nullable(value.repeatStoppedAtMillis))
                    .put("endAutoGenerated", value.endAutoGenerated).put("uncertainty", value.uncertaintyLevel);
        } catch (Exception exception) { throw invalid(exception); }
    }

    /** Preserve operational/audit content while keeping every nested reminder setting device-local. */
    public static JSONObject portableOccurrenceUpdate(JSONObject source) throws IOException {
        if (source == null) return null;
        try {
            boundedJson(source);
            JSONObject copy = new JSONObject(source.toString());
            removeReminders(copy);
            return copy;
        } catch (Exception exception) { throw invalid(exception); }
    }

    private static void removeReminders(Object value) throws Exception {
        if (value instanceof JSONObject) {
            JSONObject object = (JSONObject) value;
            object.remove("reminder_minutes_before");
            java.util.Iterator<String> keys = object.keys();
            while (keys.hasNext()) removeReminders(object.get(keys.next()));
        } else if (value instanceof JSONArray) {
            JSONArray array = (JSONArray) value;
            for (int i = 0; i < array.length(); i++) removeReminders(array.get(i));
        }
    }

    public static EventCandidate event(JSONObject value) throws IOException {
        try {
            checkCandidate(value);
            int uncertainty = value.getInt("uncertainty");
            return new EventCandidate(0, 0, value.getString("title"), millis(value, "startAt"),
                    millis(value, "endAt"), value.getString("zone"), value.getString("location"),
                    value.getString("description"), null, uncertainty != 0, null,
                    value.getString("category"), value.getBoolean("allDay"),
                    value.getBoolean("endAutoGenerated"), uncertainty, millis(value,"dueAt"),millis(value,"completedAt"),value.getBoolean("record"))
                    .withRepeat(value.isNull("recurrence") ? null : RepeatRule.fromJson(value.getJSONObject("recurrence")))
                    .withRepeatState(value.has("repeatExceptions") ? value.getJSONObject("repeatExceptions").toString() : "{}",
                            value.has("repeatStoppedAt") ? millis(value,"repeatStoppedAt") : null);
        } catch (Exception exception) { throw invalid(exception); }
    }

    public static JSONObject validate(JSONObject source) throws IOException {
        try {
            if (source == null || source.toString().getBytes(StandardCharsets.UTF_8).length > MAX_TASK_BYTES)
                throw new IOException("单条同步记录过大");
            JSONObject value = new JSONObject(source.toString());
            String kind = value.getString("kind");
            if ("task".equals(kind)) {
                only(value, "kind", "rawText", "source", "createdAt", "status", "linkText", "candidates", "attachments");
                string(value, "rawText", 1_000_000, false);
                string(value, "source", 200, false);
                string(value, "linkText", 200_000, false);
                long created = integer(value, "createdAt");
                if (created < MIN_TIME || created > MAX_TIME) throw new IOException("记录时间无效");
                String status = value.getString("status");
                if (!java.util.Arrays.asList("ready", "needs_review", "failed").contains(status))
                    throw new IOException("不支持的同步记录状态");
                JSONArray candidates = value.getJSONArray("candidates");
                if (candidates.length() > MAX_CANDIDATES) throw new IOException("单条记录的日程数量超过 30000，请整理后重试同步");
                Set<String> ids = new HashSet<>();
                for (int i = 0; i < candidates.length(); i++) {
                    JSONObject candidate = candidates.getJSONObject(i);
                    checkCandidate(candidate);
                    if (!ids.add(candidate.getString("id"))) throw new IOException("日程身份重复");
                }
                JSONArray attachments = value.getJSONArray("attachments");
                if (attachments.length() > 64) throw new IOException("单条记录最多同步 64 个附件");
                for (int i = 0; i < attachments.length(); i++) {
                    JSONObject file = attachments.getJSONObject(i);
                    only(file, "sha", "name", "mime", "size", "image");
                    if (!file.getString("sha").matches("[0-9a-f]{64}")) throw new IOException("附件校验值无效");
                    string(file, "name", 255, true); string(file, "mime", 120, true);
                    long size = integer(file, "size");
                    if (size < 0 || size > MAX_ATTACHMENT_BYTES) throw new IOException("单个同步附件不能超过 20 MB");
                    bool(file, "image");
                    if (file.getBoolean("image") && !"image/jpeg".equals(file.getString("mime")))
                        throw new IOException("同步图片需要使用 JPEG 格式");
                }
            } else if ("classroom".equals(kind)) {
                only(value,"kind","document","attachments");
                com.donglan.chrona.classroom.ClassroomDocument.validate(value.getJSONObject("document"));
                Set<String> required=com.donglan.chrona.classroom.ClassroomDocument.referencedImages(value.getJSONObject("document").getJSONObject("summary"));
                Set<String> present=new HashSet<>();JSONArray files=value.getJSONArray("attachments");
                if(files.length()>64)throw new IOException("课堂引用图片过多");
                for(int i=0;i<files.length();i++){
                    JSONObject file=files.getJSONObject(i);only(file,"sha","name","mime","size","image");
                    String name=com.donglan.chrona.classroom.ClassroomDocument.imageName(file.getString("name"));
                    if(!name.equals(file.getString("name"))||!present.add(name))throw new IOException("课堂图片名称重复或无效");
                    if(!file.getString("sha").matches("[0-9a-f]{64}")||integer(file,"size")<1||integer(file,"size")>MAX_ATTACHMENT_BYTES
                            ||!file.getBoolean("image")||!"image/jpeg".equals(file.getString("mime")))throw new IOException("课堂图片元数据无效");
                }
                if(!present.equals(required))throw new IOException("课堂图片清单与正文引用不一致");
            } else if ("merge".equals(kind)) {
                only(value,"kind","sourceTask","sourceCandidate","targetTask","targetCandidate","source");
                for(String key:new String[]{"sourceTask","targetTask"}) {
                    String task=value.getString(key);
                    if(!task.startsWith("task_")) throw new IOException("合并来源身份无效");
                    MergeLedger.candidateId(task.substring(5));
                }
                String sourceId=MergeLedger.candidateId(value.getString("sourceCandidate"));
                String targetId=MergeLedger.candidateId(value.getString("targetCandidate"));
                if(sourceId.compareTo(targetId)<=0) throw new IOException("合并身份必须严格递减");
                JSONObject snapshot=value.getJSONObject("source");
                only(snapshot,"rawText","source","createdAt","linkText","candidate");
                string(snapshot,"rawText",1_000_000,false);string(snapshot,"source",200,false);
                string(snapshot,"linkText",200_000,false);
                long created=integer(snapshot,"createdAt");
                if(created<MIN_TIME||created>MAX_TIME)throw new IOException("合并来源时间无效");
                checkCandidate(snapshot.getJSONObject("candidate"));
                if(!sourceId.equals(snapshot.getJSONObject("candidate").getString("id")))throw new IOException("合并来源日程身份不一致");
            } else if ("term".equals(kind)) {
                only(value, "kind", "index", "document");
                term(value);
            } else throw new IOException("同步格式不受支持，请将所有同步设备升级到最新版本后重试");
            return value;
        } catch (Exception exception) { throw invalid(exception); }
    }

    public static void validateId(String id, JSONObject payload) throws IOException {
        try {
            if ("task".equals(payload.getString("kind"))) {
                if (!id.matches("task_[0-9a-fA-F-]{36}")) throw new IOException("任务身份无效");
                UUID.fromString(id.substring(5));
            } else if ("classroom".equals(payload.getString("kind"))) {
                if(!id.equals(com.donglan.chrona.classroom.ClassroomDocument.syncId(payload.getJSONObject("document").getJSONObject("summary").getJSONObject("lesson"))))throw new IOException("课堂身份与内容不一致");
            } else if ("merge".equals(payload.getString("kind"))) {
                if(!id.equals("merge_"+payload.getString("sourceCandidate")))throw new IOException("合并记录身份不一致");
            } else {
                JSONObject plan = payload.getJSONObject("document").getJSONObject("plan");
                int mode = plan.getInt("mode"), index = payload.getInt("index");
                int season = (mode < 2 ? mode * 2 : mode - 2) + index;
                if (!id.equals("term_" + plan.getInt("year") + "_" + season))
                    throw new IOException("学期身份与内容不一致");
            }
        } catch (Exception exception) { throw invalid(exception); }
    }

    public static final class Term {
        public final Timetable table;
        public final AcademicTerms.Plan plan;
        public final int index;
        public final java.util.Map<String, Boolean> classification;
        Term(Timetable table, AcademicTerms.Plan plan, int index, java.util.Map<String, Boolean> classification) {
            this.table = table; this.plan = plan; this.index = index; this.classification = classification;
        }
        public AcademicTerms.View view() {
            return new AcademicTerms.View(plan.entries(table, index), table.zone, classification);
        }
    }

    public static Term term(JSONObject payload) throws IOException {
        try {
            JSONObject document = payload.getJSONObject("document");
            only(document, "format", "name", "ics", "importedAt", "zone", "plan", "enabled", "classification");
            if (integer(document, "format") != 1) throw new IOException("课表格式不受支持");
            string(document, "name", 160, true);
            String source = string(document, "ics", TimetableParser.MAX_BYTES, true);
            ZoneId zone = ZoneId.of(document.getString("zone"));
            long imported = integer(document, "importedAt");
            if (imported < MIN_TIME || imported > MAX_TIME) throw new IOException("课表导入时间无效");
            JSONObject p = document.getJSONObject("plan");
            only(p, "year", "mode", "start", "split", "end");
            AcademicTerms.Plan plan = new AcademicTerms.Plan(Math.toIntExact(integer(p, "year")),
                    Math.toIntExact(integer(p, "mode")), LocalDate.parse(p.getString("start")),
                    LocalDate.parse(p.getString("split")), LocalDate.parse(p.getString("end")));
            int index = Math.toIntExact(integer(payload, "index"));
            if (index < 0 || index >= plan.count()) throw new IOException("学期编号无效");
            JSONArray enabled = document.getJSONArray("enabled");
            if (enabled.length() != 1 || !(enabled.get(0) instanceof Number) || enabled.getInt(0) != index)
                throw new IOException("同步课表必须只包含一个启用学期");
            Timetable table = TimetableParser.parse(source, zone);
            plan.validateCoverage(table);
            JSONObject choices = document.getJSONObject("classification");
            if (choices.length() > 30_000) throw new IOException("课表分类项过多");
            java.util.Map<String, Boolean> classification = new java.util.HashMap<>();
            java.util.Iterator<String> keys = choices.keys();
            while (keys.hasNext()) {
                String key = keys.next();
                if (key.length() > 2000 || !(choices.get(key) instanceof Boolean))
                    throw new IOException("课表分类项无效");
                classification.put(key, choices.getBoolean(key));
            }
            return new Term(table, plan, index, classification);
        } catch (Exception exception) { throw invalid(exception); }
    }

    private static void checkCandidate(JSONObject value) throws Exception {
        only(value, "id", "title", "startAt", "endAt", "zone", "location", "description", "category",
                "allDay", "endAutoGenerated", "uncertainty", "dueAt", "completedAt", "record",
                "recurrence", "repeatExceptions", "repeatStoppedAt", "occurrenceUpdate");
        UUID.fromString(string(value, "id", 36, true));
        string(value, "title", 4000, true); string(value, "location", 4000, false);
        string(value, "description", 200_000, false);
        ZoneId.of(value.getString("zone"));
        String category = value.getString("category");
        if (!java.util.Arrays.asList(EventCategory.VALUES).contains(category)) throw new IOException("日程类型无效");
        Long start = millis(value, "startAt"), end = millis(value, "endAt");
        if (start != null && end != null && end < start) throw new IOException("结束时间早于开始时间");
        Long due=millis(value,"dueAt"),done=millis(value,"completedAt"); bool(value,"record");
        if((due!=null||done!=null)&&(!EventCategory.isTaskLike(category)||value.getBoolean("record"))) throw new IOException("截止与完成状态只属于待办");
        bool(value, "allDay"); bool(value, "endAutoGenerated");
        long level = integer(value, "uncertainty");
        if (level < 0 || level > 2) throw new IOException("日程确认状态无效");
        RepeatRule rule = null;
        if (!value.isNull("recurrence")) {
            rule = RepeatRule.fromJson(value.getJSONObject("recurrence"));
            Long anchor = start == null ? due : start;
            if (value.getBoolean("record") || anchor == null) throw new IOException("重复日程缺少首次时间");
            rule.validateAnchor(anchor, value.getString("zone"));
        }
        if (value.has("repeatStoppedAt")) millis(value, "repeatStoppedAt");
        if (value.has("repeatExceptions")) {
            JSONObject exceptions = value.getJSONObject("repeatExceptions");
            boundedJson(exceptions);
            if (value.isNull("recurrence") && exceptions.length() != 0) throw new IOException("单次调整缺少重复规则");
            EventCandidate template = new EventCandidate(1, 1, value.getString("title"), start, end,
                    value.getString("zone"), value.getString("location"), value.getString("description"),
                    null, level != 0, null, category, value.getBoolean("allDay"),
                    value.getBoolean("endAutoGenerated"), (int) level, due, done, value.getBoolean("record"))
                    .withRepeat(rule);
            java.util.Iterator<String> keys = exceptions.keys();
            while (keys.hasNext()) {
                String key = keys.next(); long original = Long.parseLong(key);
                if (!key.equals(Long.toString(original)) || original < MIN_TIME || original > MAX_TIME)
                    throw new IOException("单次日程身份无效");
                JSONObject edit = exceptions.getJSONObject(key);
                only(edit, "skipped", "start", "completed", "fields", "history");
                if (edit.has("skipped")) bool(edit,"skipped");
                if (edit.has("start")) millis(edit,"start");
                if (edit.has("completed")) millis(edit,"completed");
                // Validate historical fields even after a later skip/stop, without reviving that state.
                JSONObject active = new JSONObject(edit.toString());
                active.remove("skipped");
                EventCandidate series = template.withRepeatState(new JSONObject().put(key, active).toString(), null);
                RepeatOccurrences.at(series, original);
                if (edit.has("fields")) {
                    JSONObject fields = edit.getJSONObject("fields");
                    if (fields.has("reminder_minutes_before")) throw new IOException("提醒设置不能跨设备同步");
                    RepeatOccurrences.edit(series, original, fields);
                }
                if (edit.has("history")) {
                    JSONArray history = edit.getJSONArray("history");
                    for (int i = 0; i < history.length(); i++) history.getJSONObject(i);
                }
            }
        }
        if (value.has("occurrenceUpdate") && !value.isNull("occurrenceUpdate"))
            checkOccurrenceUpdate(value.getJSONObject("occurrenceUpdate"));
        if (value.getBoolean("allDay")) {
            if (start != null && Math.floorMod(start, 86_400_000L) != 0
                    || end != null && Math.floorMod(end, 86_400_000L) != 0)
                throw new IOException("全天日程必须使用 UTC 日期边界");
        }
    }

    private static void checkOccurrenceUpdate(JSONObject value) throws Exception {
        boundedJson(value);
        only(value, "state", "runId", "position", "series_id", "original", "original_date", "baseline",
                "target_snapshot", "fields", "before", "preview", "reason", "applications", "validation");
        String state = string(value, "state", 20, true);
        if (!java.util.Arrays.asList("pending", "invalid", "new", "applied").contains(state))
            throw new IOException("单次更新状态无效");
        string(value, "runId", 200, true);
        long position = integer(value, "position");
        if (position < 0 || position > Integer.MAX_VALUE) throw new IOException("单次更新位置无效");
        boolean target = "pending".equals(state) || "applied".equals(state);
        if (target || value.has("series_id")) {
            String id = string(value, "series_id", 36, true);
            if (!UUID.fromString(id).toString().equalsIgnoreCase(id)) throw new IOException("单次更新系列身份无效");
        }
        if ((target || value.has("original")) && millis(value, "original") == null)
            throw new IOException("单次更新缺少原定时间");
        for (String key : new String[]{"fields", "preview", "before", "target_snapshot"}) {
            if (!value.has(key)) continue;
            JSONObject snapshot = value.getJSONObject(key);
            if (snapshot.has("reminder_minutes_before")) throw new IOException("提醒设置不能跨设备同步");
        }
        if (value.has("applications")) {
            JSONArray applications = value.getJSONArray("applications");
            for (int i = 0; i < applications.length(); i++) applications.getJSONObject(i);
        }
    }

    private static void boundedJson(Object value) throws Exception {
        String json = value.toString();
        if (json == null || json.getBytes(StandardCharsets.UTF_8).length > MAX_TASK_BYTES)
            throw new IOException("单次更新记录过大");
        boundedJson(value, 0, new int[]{1_000_000});
    }

    private static void boundedJson(Object value, int depth, int[] remaining) throws Exception {
        if (depth > 32 || --remaining[0] < 0) throw new IOException("单次更新记录结构过大");
        if (value instanceof JSONObject) {
            JSONObject object = (JSONObject) value;
            java.util.Iterator<String> keys = object.keys();
            while (keys.hasNext()) {
                String key = keys.next();
                if (key.length() > 4000 || key.indexOf('\0') >= 0) throw new IOException("单次更新记录字段无效");
                boundedJson(object.get(key), depth + 1, remaining);
            }
        } else if (value instanceof JSONArray) {
            JSONArray array = (JSONArray) value;
            for (int i = 0; i < array.length(); i++) boundedJson(array.get(i), depth + 1, remaining);
        } else if (value instanceof String) {
            if (((String) value).indexOf('\0') >= 0) throw new IOException("单次更新记录文本无效");
        } else if (value != JSONObject.NULL && !(value instanceof Number) && !(value instanceof Boolean)) {
            throw new IOException("单次更新记录结构无效");
        }
    }

    private static Long millis(JSONObject value, String key) throws Exception {
        if (!value.has(key)) throw new IOException("同步记录缺少时间字段");
        if (value.isNull(key)) return null;
        long millis = integer(value, key);
        if (millis < MIN_TIME || millis > MAX_TIME) throw new IOException("日程时间无效");
        return millis;
    }
    private static long integer(JSONObject value, String key) throws Exception {
        Object item = value.get(key);
        if (!(item instanceof Number) || !item.toString().matches("-?(0|[1-9][0-9]*)"))
            throw new IOException("同步记录整数格式无效");
        return Long.parseLong(item.toString());
    }
    private static void bool(JSONObject value, String key) throws Exception {
        if (!(value.get(key) instanceof Boolean)) throw new IOException("同步记录开关格式无效");
    }
    private static String string(JSONObject value, String key, int maximum, boolean required) throws Exception {
        Object raw = value.get(key);
        if (!(raw instanceof String)) throw new IOException("同步记录文本格式无效");
        String result = (String) raw;
        if (result.length() > maximum || required && result.trim().isEmpty() || result.indexOf('\0') >= 0)
            throw new IOException("同步记录文本长度或内容无效");
        return result;
    }
    private static void only(JSONObject value, String... fields) throws IOException {
        Set<String> allowed = new HashSet<>(java.util.Arrays.asList(fields));
        java.util.Iterator<String> keys = value.keys();
        while (keys.hasNext()) if (!allowed.contains(keys.next())) throw new IOException("同步记录包含不支持的字段");
    }
    private static Object nullable(Object value) { return value == null ? JSONObject.NULL : value; }
    private static String text(String value, String fallback) { return value == null || value.isEmpty() ? fallback : value; }
    private static IOException invalid(Exception exception) {
        return exception instanceof IOException ? (IOException) exception : new IOException("同步记录格式无效", exception);
    }
}
