package com.donglan.chrona.ai;

import com.donglan.chrona.data.EventCandidate;
import org.json.JSONObject;
import org.json.JSONArray;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZonedDateTime;

/** Real model normalization and transport-response parsing, with deterministic clocks. */
public final class ScheduleExecutionCheck {
    private static final long MINUTE = 60_000L;
    private static final long HOUR = 60 * MINUTE;
    private static final long NOW = at("2026-10-19T02:00:00Z"); // 10:00 Shanghai
    private static int checks;

    public static void main(String[] args) throws Exception {
        JSONObject today = base("homework", "2026-10-19", "20:00");
        EventCandidate mid = parse(today, NOW, 600, 1320);
        check(mid.startAtMillis == NOW + 5 * HOUR && mid.endAtMillis == NOW + 5 * HOUR + 30 * MINUTE,
                "today due chooses midpoint and thirty minutes");
        check(mid.dueAtMillis == NOW + 10 * HOUR && mid.needsConfirmation && mid.uncertaintyLevel == 2,
                "due retained and suggested execution requires confirmation");
        check(mid.endAutoGenerated && mid.description.contains("执行建议"), "default end provenance and suggestion visible");
        EventCandidate explicitReminder = parse(base("task", "2026-10-19", "20:00")
                .put("reminder_specified", true).put("reminder_minutes_before", 15), NOW, 600, 1320);
        check(explicitReminder.reminderMinutesBefore == 15
                && explicitReminder.reminderAnchor().equals(explicitReminder.dueAtMillis),
                "execution suggestion preserves explicit reminder and deadline anchor");
        check(parse(base("task", "2026-10-19", "20:00").put("reminder_specified", true), NOW, 600, 1320)
                .reminderMinutesBefore == null, "execution suggestion preserves explicit no-reminder");
        JSONObject distant = base("task", "2026-10-23", "20:00");
        EventCandidate chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-22T02:00:00Z"), "distant midpoint moves to nearest complete work window");
        distant.put("suggested_start", time("2026-10-21", "16:00"));
        chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-21T08:00:00Z"), "model workload choice retained inside lead range");
        distant.put("suggested_start", time("2026-10-01", "12:00"));
        chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == chosen.dueAtMillis - 72 * HOUR, "model suggestion clamped to three-day earliest start");
        distant.put("suggested_start", time("2026-10-25", "12:00"));
        chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == chosen.dueAtMillis - 6 * HOUR, "model suggestion clamped to six-hour latest start");
        today.put("duration_minutes", 90);
        chosen = parse(today, NOW, 600, 1320);
        check(chosen.endAtMillis - chosen.startAtMillis == 90 * MINUTE && !chosen.endAutoGenerated,
                "explicit or user-preferred duration preserved");
        today.put("duration_minutes", JSONObject.NULL).put("suggested_start", time("2026-10-19", "21:59"));
        chosen = parse(today, NOW, 600, 1320);
        check(chosen.startAtMillis == NOW + 5 * HOUR, "near-deadline model suggestion cannot displace midpoint");
        JSONObject lateDue = base("task", "2026-10-20", "02:00")
                .put("suggested_start", time("2026-10-19", "21:59"));
        chosen = parse(lateDue, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-19T10:00:00Z")
                && chosen.endAtMillis == at("2026-10-19T10:30:00Z"), "late model suggestion cannot displace near-deadline midpoint");
        JSONObject nearDue = base("task", "2026-10-19", "10:20");
        chosen = parse(nearDue, NOW, 600, 1320);
        check(chosen.startAtMillis == null && chosen.endAtMillis == null && chosen.dueAtMillis == NOW + 20 * MINUTE
                && chosen.needsConfirmation, "insufficient duration preserves deadline without fake interval");
        chosen = parse(base("task", "2026-10-20", "05:00"), at("2026-10-19T15:00:00Z"), 600, 1320);
        check(chosen.startAtMillis == null && chosen.endAtMillis == null, "no work window before due");
        chosen = parse(base("homework", "2026-10-20", "05:00"), at("2026-10-19T15:00:00Z"), 1320, 360);
        check(chosen.startAtMillis == at("2026-10-19T18:00:00Z"), "overnight daily window contains midpoint");
        chosen = parse(base("homework", "2026-10-20", "05:00"), at("2026-10-19T17:00:00Z"), 1320, 360);
        check(chosen.startAtMillis == at("2026-10-19T19:00:00Z"), "after-midnight start uses preceding-day work window");
        JSONObject explicit = base("task", "2026-10-19", "20:00")
                .put("start", time("2026-10-19", "08:00")).put("end", time("2026-10-19", "09:00"));
        chosen = parse(explicit, NOW, 600, 1320);
        check(chosen.startAtMillis == NOW - 2 * HOUR && chosen.endAtMillis == NOW - HOUR,
                "source times outside working hours preserved even if provenance false");
        explicit.put("start", JSONObject.NULL).put("end", JSONObject.NULL).put("execution_time_explicit", true);
        chosen = parse(explicit, NOW, 600, 1320);
        check(chosen.startAtMillis == null && chosen.needsConfirmation, "unresolved explicit execution intention never overwritten");
        check(parse(base("event", "2026-10-19", "20:00"), NOW, 600, 1320).startAtMillis == null,
                "event never receives automatic execution");
        check(parse(base("task", null, null), NOW, 600, 1320).startAtMillis == null, "no deadline stays unscheduled");
        check(parse(base("task", "2026-10-19", "09:00"), NOW, 600, 1320).startAtMillis == null,
                "elapsed due stays unscheduled");
        JSONObject repeat = base("homework", "2026-10-19", "20:00").put("recurrence", new JSONObject()
                .put("frequency", "weekly").put("interval", 1).put("weekdays", new JSONArray().put(1))
                .put("until", JSONObject.NULL).put("count", JSONObject.NULL));
        chosen = parse(repeat, NOW, 600, 1320);
        check(chosen.startAtMillis == null && chosen.repeatRule != null && chosen.needsConfirmation,
                "recurrence retains deadline anchor and asks for execution confirmation");
        chosen = parse(base("task", "2026-10-19", "20:00").put("duration_minutes", 900), NOW, 600, 1320);
        check(chosen.startAtMillis == null, "oversized explicit duration not silently shortened");
        long later = NOW + 7 * HOUR + 12_345;
        chosen = parse(base("task", "2026-10-19", "20:00")
                .put("suggested_start", time("2026-10-19", "11:00")), later, 600, 1320);
        check(chosen.startAtMillis >= later && chosen.startAtMillis % MINUTE == 0,
                "queued extraction uses actual execution clock and next whole minute");
        JSONObject relative = base("task", null, null).put("due", new JSONObject().put("day_offset", 1).put("time", "20:00"));
        chosen = parse(relative, NOW + 24 * HOUR, 600, 1320);
        check(chosen.dueAtMillis == at("2026-10-20T12:00:00Z") && chosen.startAtMillis >= NOW + 24 * HOUR,
                "original reference clock resolves relative due while fresh clock limits scheduling");
        JSONObject response = new JSONObject().put("choices", new JSONArray().put(new JSONObject()
                .put("message", new JSONObject().put("content", new JSONObject().put("events", new JSONArray()
                        .put(base("task", "2026-10-19", "20:00"))).toString()))));
        chosen = ChatCompletionClient.parseResponse(1, response.toString(), NOW, "Asia/Shanghai", NOW, 600, 1320).candidates.get(0);
        check(chosen.startAtMillis == mid.startAtMillis.longValue(), "actual response parser applies execution policy");
        JSONObject missing = base("task", "2026-10-19", "20:00"); missing.remove("execution_time_explicit");
        response.getJSONArray("choices").getJSONObject(0).getJSONObject("message")
                .put("content", new JSONObject().put("events", new JSONArray().put(missing)).toString());
        try { ChatCompletionClient.parseResponse(1, response.toString(), NOW, "Asia/Shanghai"); throw new AssertionError("missing provenance accepted"); }
        catch (ChatCompletionClient.ResponseException expected) { checks++; }
        JSONObject props = SchedulePrompt.schema().getJSONObject("properties").getJSONObject("events")
                .getJSONObject("items");
        check(props.getJSONArray("required").toList().contains("execution_time_explicit")
                && props.getJSONArray("required").toList().contains("suggested_start"), "provenance and suggestion required by schema");
        JSONObject foreignZone = base("task", "2026-10-19", "23:00").put("time_zone_id", "UTC")
                .put("suggested_start", time("2026-10-19", "20:00"));
        chosen = parse(foreignZone, NOW, 600, 1320);
        ZonedDateTime localStart = Instant.ofEpochMilli(chosen.startAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
        check(localStart.getHour() >= 10 && localStart.getHour() < 22,
                "work hours use local request zone rather than explicit deadline zone");
        JSONObject fold = base("task", "2026-11-01", "04:00").put("time_zone_id", "America/New_York");
        chosen = SemanticEventNormalizer.fromJson(7, fold, NOW, "America/New_York",
                at("2026-11-01T04:00:00Z"), 90, 150);
        check(chosen.startAtMillis != null, "fall-back window remains usable");
        for (long minute = chosen.startAtMillis; minute < chosen.endAtMillis; minute += MINUTE) {
            ZonedDateTime local = Instant.ofEpochMilli(minute).atZone(ZoneId.of("America/New_York"));
            int clock = local.getHour() * 60 + local.getMinute();
            check(clock >= 90 && clock < 150, "fall-back cannot cross an out-of-window repeated clock");
        }
        JSONObject gap = base("task", "2027-03-14", "03:30").put("time_zone_id", "America/New_York");
        chosen = SemanticEventNormalizer.fromJson(7, gap, NOW, "America/New_York",
                at("2027-03-14T06:30:00Z"), 150, 240);
        check(chosen.startAtMillis == at("2027-03-14T07:00:00Z"), "spring gap begins at first real allowed instant");
        // A sweep catches edge intersections without relying on particular chosen midpoints.
        for (int hour = 0; hour < 24; hour++) for (int remaining : new int[]{1, 12, 25, 50, 100}) {
            long now = NOW + hour * HOUR;
            ZonedDateTime due = Instant.ofEpochMilli(now + remaining * HOUR).atZone(ZoneId.of("Asia/Shanghai"));
            chosen = parse(base("task", due.toLocalDate().toString(), due.toLocalTime().toString()), now, 600, 1320);
            check(chosen.dueAtMillis == now + remaining * HOUR, "sweep never changes due");
            if (chosen.startAtMillis == null) continue;
            ZonedDateTime begin = Instant.ofEpochMilli(chosen.startAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
            ZonedDateTime end = Instant.ofEpochMilli(chosen.endAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
            check(chosen.startAtMillis >= now && chosen.endAtMillis <= chosen.dueAtMillis
                    && chosen.endAtMillis - chosen.startAtMillis == 30 * MINUTE
                    && begin.toLocalDate().equals(end.toLocalDate()) && begin.getHour() >= 10
                    && (end.getHour() < 22 || end.getHour() == 22 && end.getMinute() == 0), "sweep fits whole work interval");
        }
        System.out.println("ScheduleExecutionCheck: " + checks + " checks passed");
    }

    private static EventCandidate parse(JSONObject event, long schedulingNow, int start, int end) throws Exception {
        return SemanticEventNormalizer.fromJson(7, event, NOW, "Asia/Shanghai", schedulingNow, start, end);
    }
    private static JSONObject base(String category, String date, String clock) throws Exception {
        return new JSONObject().put("title", "完成报告").put("category", category).put("all_day", false)
                .put("needs_confirmation", false).put("uncertainty_level", 0).put("time_zone_id", "Asia/Shanghai")
                .put("start", JSONObject.NULL).put("end", JSONObject.NULL)
                .put("due", date == null ? JSONObject.NULL : time(date, clock))
                .put("suggested_start", JSONObject.NULL).put("execution_time_explicit", false)
                .put("duration_minutes", JSONObject.NULL).put("location", JSONObject.NULL).put("description", "原始要求")
                .put("reminder_minutes_before", JSONObject.NULL).put("reminder_specified", false).put("recurrence", JSONObject.NULL);
    }
    private static JSONObject time(String date, String clock) throws Exception {
        return new JSONObject().put("date", date).put("time", clock);
    }
    private static long at(String value) { return Instant.parse(value).toEpochMilli(); }
    private static void check(boolean condition, String label) {
        if (!condition) throw new AssertionError(label);
        checks++;
    }
}
