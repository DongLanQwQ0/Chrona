package com.donglan.chrona.ai;

import com.donglan.chrona.data.EventCandidate;
import org.json.JSONObject;
import org.json.JSONArray;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZonedDateTime;
import java.util.List;

/** Real model normalization and transport-response parsing, with deterministic clocks. */
public final class ScheduleExecutionCheck {
    private static final long MINUTE = 60_000L;
    private static final long HOUR = 60 * MINUTE;
    private static final long NOW = at("2026-10-19T02:00:00Z"); // 10:00 Shanghai
    private static int checks;

    public static void main(String[] args) throws Exception {
        JSONObject today = base("homework", "2026-10-19", "20:00");
        EventCandidate mid = parse(today, NOW, 600, 1320);
        check(mid.startAtMillis == NOW + 4 * HOUR + 45 * MINUTE && mid.endAtMillis == NOW + 5 * HOUR + 15 * MINUTE,
                "today due chooses feasible-start midpoint and thirty minutes");
        check(mid.dueAtMillis == NOW + 10 * HOUR && mid.needsConfirmation && mid.uncertaintyLevel == 2,
                "due retained and suggested execution requires confirmation");
        check(mid.endAutoGenerated && mid.description.contains("执行建议"), "default end provenance and suggestion visible");
        EventCandidate explicitReminder = parse(base("task", "2026-10-19", "20:00")
                .put("reminder_specified", true).put("reminder_minutes_before", 15), NOW, 600, 1320);
        check(explicitReminder.reminderMinutesBefore == 15
                && explicitReminder.reminderAnchor().equals(explicitReminder.dueAtMillis),
                "execution suggestion preserves explicit reminder and deadline anchor");
        check(parse(base("task", "2026-10-19", "20:00").put("reminder_specified", true), NOW, 600, 1320)
                .reminderMinutesBefore == null, "execution suggestion preserves explicit no-reminder");
        JSONObject distant = base("task", "2026-10-23", "20:00");
        EventCandidate chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-21T06:45:00Z"), "distant midpoint uses the whole feasible-start horizon");
        distant.put("suggested_start", time("2026-10-21", "16:00"));
        chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-21T08:00:00Z"), "model workload choice retained inside lead range");
        distant.put("suggested_start", time("2026-10-01", "12:00"));
        chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == NOW, "past model suggestion clamps to now without a three-day restriction");
        distant.put("suggested_start", time("2026-10-25", "12:00"));
        chosen = parse(distant, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-22T09:07:00Z"), "late model suggestion reserves a horizon-proportional review buffer");
        today.put("duration_minutes", 90);
        chosen = parse(today, NOW, 600, 1320);
        check(chosen.endAtMillis - chosen.startAtMillis == 90 * MINUTE && !chosen.endAutoGenerated,
                "explicit or user-preferred duration preserved");
        today.put("duration_minutes", JSONObject.NULL).put("suggested_start", time("2026-10-19", "21:59"));
        chosen = parse(today, NOW, 600, 1320);
        check(chosen.startAtMillis == NOW + 4 * HOUR + 45 * MINUTE, "near-deadline model suggestion cannot displace feasible-start midpoint");
        JSONObject lateDue = base("task", "2026-10-20", "02:00")
                .put("suggested_start", time("2026-10-19", "21:59"));
        chosen = parse(lateDue, NOW, 600, 1320);
        check(chosen.startAtMillis == at("2026-10-19T09:45:00Z")
                && chosen.endAtMillis == at("2026-10-19T10:15:00Z"), "late model suggestion cannot displace near-deadline midpoint");
        JSONObject nearDue = base("task", "2026-10-19", "10:20");
        chosen = parse(nearDue, NOW, 600, 1320);
        check(chosen.startAtMillis == null && chosen.endAtMillis == null && chosen.dueAtMillis == NOW + 20 * MINUTE
                && chosen.needsConfirmation, "insufficient duration preserves deadline without fake interval");
        chosen = parse(base("task", "2026-10-20", "05:00"), at("2026-10-19T15:00:00Z"), 600, 1320);
        check(chosen.startAtMillis == null && chosen.endAtMillis == null, "no work window before due");
        chosen = parse(base("homework", "2026-10-20", "05:00"), at("2026-10-19T15:00:00Z"), 1320, 360);
        check(chosen.startAtMillis == at("2026-10-19T17:45:00Z"), "overnight daily window contains feasible-start midpoint");
        chosen = parse(base("homework", "2026-10-20", "05:00"), at("2026-10-19T17:00:00Z"), 1320, 360);
        check(chosen.startAtMillis == at("2026-10-19T18:45:00Z"), "after-midnight start uses preceding-day work window");
        JSONObject explicit = base("task", "2026-10-19", "20:00")
                .put("start", time("2026-10-19", "08:00")).put("end", time("2026-10-19", "09:00"));
        chosen = parse(explicit, NOW, 600, 1320);
        check(chosen.startAtMillis == NOW - 2 * HOUR && chosen.endAtMillis == NOW - HOUR,
                "source times outside working hours preserved even if provenance false");
        explicit.put("start", JSONObject.NULL).put("end", JSONObject.NULL).put("execution_time_explicit", true);
        chosen = parse(explicit, NOW, 600, 1320);
        check(chosen.startAtMillis == null && chosen.needsConfirmation, "unresolved explicit execution intention never overwritten");
        check(parse(base("event", "2026-10-19", "20:00"), NOW, 600, 1320).startAtMillis == null,
                "event never receives automatic execution");
        check(parse(base("task", null, null), NOW, 600, 1320).startAtMillis == null, "no deadline stays unscheduled");
        check(parse(base("task", "2026-10-19", "09:00"), NOW, 600, 1320).startAtMillis == null,
                "elapsed due stays unscheduled");
        JSONObject repeat = base("homework", "2026-10-19", "20:00").put("recurrence", new JSONObject()
                .put("frequency", "weekly").put("interval", 1).put("weekdays", new JSONArray().put(1))
                .put("until", JSONObject.NULL).put("count", JSONObject.NULL));
        chosen = parse(repeat, NOW, 600, 1320);
        check(chosen.startAtMillis == null && chosen.repeatRule != null && chosen.needsConfirmation,
                "recurrence retains deadline anchor and asks for execution confirmation");
        chosen = parse(base("task", "2026-10-19", "20:00").put("duration_minutes", 900), NOW, 600, 1320);
        check(chosen.startAtMillis == null, "oversized explicit duration not silently shortened");
        long later = NOW + 7 * HOUR + 12_345;
        chosen = parse(base("task", "2026-10-19", "20:00")
                .put("suggested_start", time("2026-10-19", "11:00")), later, 600, 1320);
        check(chosen.startAtMillis >= later && chosen.startAtMillis % MINUTE == 0,
                "queued extraction uses actual execution clock and next whole minute");
        JSONObject relative = base("task", null, null).put("due", new JSONObject().put("day_offset", 1).put("time", "20:00"));
        chosen = parse(relative, NOW + 24 * HOUR, 600, 1320);
        check(chosen.dueAtMillis == at("2026-10-20T12:00:00Z") && chosen.startAtMillis >= NOW + 24 * HOUR,
                "original reference clock resolves relative due while fresh clock limits scheduling");
        JSONObject response = new JSONObject().put("choices", new JSONArray().put(new JSONObject()
                .put("message", new JSONObject().put("content", new JSONObject().put("events", new JSONArray()
                        .put(TimeAssessmentCheck.evidence(base("task", "2026-10-19", "20:00")))).toString()))));
        chosen = ChatCompletionClient.parseResponse(1, response.toString(), NOW, "Asia/Shanghai", NOW, 600, 1320).candidates.get(0);
        check(chosen.startAtMillis == mid.startAtMillis.longValue(), "actual response parser applies execution policy");
        JSONObject missing = base("task", "2026-10-19", "20:00"); missing.remove("execution_time_explicit");
        response.getJSONArray("choices").getJSONObject(0).getJSONObject("message")
                .put("content", new JSONObject().put("events", new JSONArray().put(missing)).toString());
        try { ChatCompletionClient.parseResponse(1, response.toString(), NOW, "Asia/Shanghai"); throw new AssertionError("missing provenance accepted"); }
        catch (ChatCompletionClient.ResponseException expected) { checks++; }
        JSONObject props = SchedulePrompt.schema().getJSONObject("properties").getJSONObject("events")
                .getJSONObject("items");
        check(props.getJSONArray("required").toList().contains("execution_time_explicit")
                && props.getJSONArray("required").toList().contains("suggested_start"), "provenance and suggestion required by schema");
        JSONObject foreignZone = base("task", "2026-10-19", "23:00").put("time_zone_id", "UTC")
                .put("suggested_start", time("2026-10-19", "20:00"));
        chosen = parse(foreignZone, NOW, 600, 1320);
        ZonedDateTime localStart = Instant.ofEpochMilli(chosen.startAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
        check(localStart.getHour() >= 10 && localStart.getHour() < 22,
                "work hours use local request zone rather than explicit deadline zone");
        JSONObject fold = base("task", "2026-11-01", "04:00").put("time_zone_id", "America/New_York");
        chosen = SemanticEventNormalizer.fromJson(7, fold, NOW, "America/New_York",
                at("2026-11-01T04:00:00Z"), 90, 150);
        check(chosen.startAtMillis != null, "fall-back window remains usable");
        for (long minute = chosen.startAtMillis; minute < chosen.endAtMillis; minute += MINUTE) {
            ZonedDateTime local = Instant.ofEpochMilli(minute).atZone(ZoneId.of("America/New_York"));
            int clock = local.getHour() * 60 + local.getMinute();
            check(clock >= 90 && clock < 150, "fall-back cannot cross an out-of-window repeated clock");
        }
        JSONObject gap = base("task", "2027-03-14", "03:30").put("time_zone_id", "America/New_York");
        chosen = SemanticEventNormalizer.fromJson(7, gap, NOW, "America/New_York",
                at("2027-03-14T06:30:00Z"), 150, 240);
        check(chosen.startAtMillis == at("2027-03-14T07:00:00Z"), "spring gap begins at first real allowed instant");
        // A sweep catches edge intersections without relying on particular chosen midpoints.
        for (int hour = 0; hour < 24; hour++) for (int remaining : new int[]{1, 12, 25, 50, 100}) {
            long now = NOW + hour * HOUR;
            ZonedDateTime due = Instant.ofEpochMilli(now + remaining * HOUR).atZone(ZoneId.of("Asia/Shanghai"));
            chosen = parse(base("task", due.toLocalDate().toString(), due.toLocalTime().toString()), now, 600, 1320);
            check(chosen.dueAtMillis == now + remaining * HOUR, "sweep never changes due");
            if (chosen.startAtMillis == null) continue;
            ZonedDateTime begin = Instant.ofEpochMilli(chosen.startAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
            ZonedDateTime end = Instant.ofEpochMilli(chosen.endAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
            check(chosen.startAtMillis >= now && chosen.endAtMillis <= chosen.dueAtMillis
                    && chosen.endAtMillis - chosen.startAtMillis == 30 * MINUTE
                    && begin.toLocalDate().equals(end.toLocalDate()) && begin.getHour() >= 10
                    && (end.getHour() < 22 || end.getHour() == 22 && end.getMinute() == 0), "sweep fits whole work interval");
        }
        wholePeriodSingles();
        spreadPlans();
        System.out.println("ScheduleExecutionCheck: " + checks + " checks passed");
    }

    private static void wholePeriodSingles() throws Exception {
        for (int days : new int[]{10, 30, 60}) {
            long due = NOW + days * 24 * HOUR;
            for (String category : new String[]{"task", "homework"}) {
                JSONObject event = base(category, null, null).put("title", "完成常规项目")
                        .put("due", clock(due));
                EventCandidate midpoint = parse(event, NOW, 0, 1439);
                long expected = NOW + (due - 30 * MINUTE - NOW) / 2;
                check(midpoint.startAtMillis == expected && midpoint.endAtMillis == expected + 30 * MINUTE,
                        "generic single item uses full feasible-start period: " + category + "/" + days);
                check(midpoint.dueAtMillis == due && midpoint.needsConfirmation && midpoint.uncertaintyLevel == 2,
                        "whole-period suggestion retains due and review requirement");
                long early = NOW + 24 * HOUR;
                event.put("suggested_start", clock(early));
                EventCandidate proposed = parse(event, NOW, 600, 1320);
                check(proposed.startAtMillis == early, "early model choice remains available: " + days);
                event.put("suggested_start", clock(due - HOUR));
                proposed = parse(event, NOW, 0, 1439);
                long slack = due - 30 * MINUTE - NOW;
                long latestTarget = due - 30 * MINUTE - slack / 4;
                latestTarget = latestTarget / MINUTE * MINUTE;
                check(proposed.startAtMillis == latestTarget && proposed.endAtMillis < due - 24 * HOUR,
                        "late choice leaves proportional modification and submission time: " + days);
            }
        }
        JSONObject effort = base("task", "2026-10-29", "20:00");
        EventCandidate shortWork = parse(effort.put("duration_minutes", 30), NOW, 0, 1439);
        EventCandidate longWork = parse(effort.put("duration_minutes", 600), NOW, 0, 1439);
        check(longWork.startAtMillis < shortWork.startAtMillis
                && longWork.endAtMillis - longWork.startAtMillis == 600 * MINUTE,
                "longer workload gets an earlier default target without shortening work");
        effort.put("due", time("2026-10-20", "16:00"))
                .put("suggested_start", time("2026-10-20", "15:00"));
        shortWork = parse(effort.put("duration_minutes", 30), NOW, 600, 599);
        longWork = parse(effort.put("duration_minutes", 600), NOW, 600, 599);
        check(longWork.startAtMillis < shortWork.startAtMillis
                && longWork.dueAtMillis - longWork.endAtMillis > shortWork.dueAtMillis - shortWork.endAtMillis,
                "longer workload advances late suggestions and increases reserved review time");
        JSONObject narrow = base("task", "2026-10-20", "10:32").put("duration_minutes", 31)
                .put("suggested_start", time("2026-10-20", "10:00"));
        EventCandidate onlyWindow = parse(narrow, NOW + MINUTE, 600, 631);
        check(onlyWindow.startAtMillis == at("2026-10-20T02:00:00Z"),
                "nearest full work window remains usable outside preferred buffer target");
        EventCandidate exact = parse(base("task", "2026-10-19", "10:30"), NOW, 600, 1320);
        check(exact.startAtMillis == NOW && exact.endAtMillis == exact.dueAtMillis.longValue(),
                "exact-duration short deadline stays executable without mandatory buffer");
    }

    private static void spreadPlans() throws Exception {
        for (int days : new int[]{10, 30, 60}) {
            int count = days == 30 ? 4 : 6;
            long due = NOW + days * 24 * HOUR;
            JSONArray steps = steps("project", count, due);
            // Even a stale final-days suggestion must no longer pull all grouped steps late.
            for (int i=0;i<count;i++) steps.getJSONObject(i).put("suggested_start", clock(due-24*HOUR));
            String original=steps.toString();
            List<EventCandidate> planned=batch(steps,NOW,600,1320);
            check(steps.toString().equals(original),"planning never rewrites extracted facts");
            check(planned.get(0).startAtMillis < NOW + days*24*HOUR/4,"long-horizon plan starts early: "+days);
            check(planned.get(count-1).startAtMillis-planned.get(0).startAtMillis > days*24*HOUR/2,
                    "steps span more than half the available period: "+days);
            long previous=NOW;
            for(EventCandidate item:planned) {
                check(item.startAtMillis>=previous && item.endAtMillis<=due,"ordered nonoverlapping steps before deadline");
                check(item.dueAtMillis==due&&item.uncertaintyLevel==2&&item.needsConfirmation,"original due retained and all suggestions require review");
                check(item.startAtMillis>=NOW&&item.endAtMillis-item.startAtMillis==30*MINUTE,"full default duration retained");
                ZonedDateTime start=Instant.ofEpochMilli(item.startAtMillis).atZone(ZoneId.of("Asia/Shanghai"));
                check(start.getHour()>=10&&start.getHour()<22,"spread target respects work window");
                previous=item.endAtMillis;
            }
        }
        long due=NOW+30*24*HOUR;
        JSONArray weighted=steps("report",3,due);
        weighted.getJSONObject(0).put("duration_minutes",120);
        weighted.getJSONObject(1).put("duration_minutes",45);
        weighted.getJSONObject(2).put("duration_minutes",90);
        List<EventCandidate> plan=batch(weighted,NOW,600,1320);
        check(plan.get(0).endAtMillis-plan.get(0).startAtMillis==120*MINUTE
                &&plan.get(1).endAtMillis-plan.get(1).startAtMillis==45*MINUTE
                &&plan.get(2).endAtMillis-plan.get(2).startAtMillis==90*MINUTE,"unequal workloads keep their durations");
        long gap1=plan.get(1).startAtMillis-plan.get(0).endAtMillis;
        long gap2=plan.get(2).startAtMillis-plan.get(1).endAtMillis;
        check(Math.abs(gap1-gap2)<24*HOUR,"workload-aware free gaps remain roughly uniform");

        JSONArray fixed=steps("project",4,due);
        long milestone=NOW+14*24*HOUR;
        fixed.getJSONObject(1).put("execution_time_explicit",true).put("start",clock(milestone))
                .put("end",clock(milestone+2*HOUR));
        plan=batch(fixed,NOW,600,1320);
        check(plan.get(1).startAtMillis==milestone&&plan.get(1).endAtMillis==milestone+2*HOUR,"explicit fixed execution is untouched");
        check(plan.get(0).endAtMillis<=milestone&&plan.get(2).startAtMillis>=milestone+2*HOUR
                &&plan.get(3).startAtMillis>plan.get(2).endAtMillis,"fixed execution splits the planning horizon");
        fixed.getJSONObject(0).put("due",clock(NOW+3*24*HOUR));
        plan=batch(fixed,NOW,600,1320);
        check(plan.get(0).dueAtMillis==NOW+3*24*HOUR&&plan.get(0).endAtMillis<=plan.get(0).dueAtMillis,"early child deadline overrides its target without changing due");

        JSONArray preparation=steps("exam-preparation",4,NOW+60*24*HOUR);
        for(int i=0;i<preparation.length();i++)preparation.getJSONObject(i).put("due",JSONObject.NULL);
        plan=batch(preparation,NOW,600,1320);
        check(plan.get(0).startAtMillis<NOW+15*24*HOUR&&plan.get(3).startAtMillis>NOW+40*24*HOUR,"fixed future activity can anchor preparation without a task deadline");
        for(EventCandidate item:plan)check(item.dueAtMillis==null&&item.reminderMinutesBefore==null,"preparation boundary does not fabricate a deadline or reminder");
        JSONArray expired=steps("expired-boundary",2,due);
        for(int i=0;i<2;i++)expired.getJSONObject(i).put("plan_until",clock(NOW-HOUR));
        plan=batch(expired,NOW,600,1320);
        for(EventCandidate item:plan)check(item.startAtMillis==null&&item.dueAtMillis==due&&item.needsConfirmation,
                "expired preparation boundary does not fall back to future standalone scheduling");

        JSONArray independent=steps("ignored",2,due);
        for(int i=0;i<2;i++)independent.getJSONObject(i).put("plan_group",JSONObject.NULL).put("plan_until",JSONObject.NULL);
        plan=batch(independent,NOW,600,1320);
        check(plan.get(0).startAtMillis<NOW+16*24*HOUR&&plan.get(1).startAtMillis.equals(plan.get(0).startAtMillis),"unrelated same-deadline tasks retain whole-period standalone policy");
        JSONArray a=steps("a",2,due),b=steps("b",2,due);
        plan=batch(new JSONArray().put(a.get(0)).put(b.get(0)).put(a.get(1)).put(b.get(1)),NOW,600,1320);
        check(plan.get(0).startAtMillis.equals(plan.get(1).startAtMillis)
                &&plan.get(2).startAtMillis.equals(plan.get(3).startAtMillis),"interleaved independent groups do not merge");

        JSONArray crowded=steps("crowded",2,NOW+HOUR);
        for(int i=0;i<2;i++)crowded.getJSONObject(i).put("duration_minutes",45);
        plan=batch(crowded,NOW,600,1320);
        check(plan.get(0).startAtMillis!=null&&plan.get(1).startAtMillis==null
                &&plan.get(1).dueAtMillis==NOW+HOUR&&plan.get(1).needsConfirmation,"insufficient group time keeps unfinished step pending instead of overlapping");
        plan=batch(steps("queued",3,due),NOW+20*24*HOUR,1320,360);
        for(EventCandidate item:plan) {
            check(item.startAtMillis>=NOW+20*24*HOUR&&item.endAtMillis<=due,"queue delay uses fresh scheduling clock");
            int hour=Instant.ofEpochMilli(item.startAtMillis).atZone(ZoneId.of("Asia/Shanghai")).getHour();
            check(hour>=22||hour<6,"group placement supports overnight work window");
        }
        JSONObject schema=SchedulePrompt.schema().getJSONObject("properties").getJSONObject("events").getJSONObject("items");
        check(schema.getJSONArray("required").toList().contains("plan_group")
                &&schema.getJSONArray("required").toList().contains("plan_until"),"plan provenance is explicit in schema");
        for(Object invalid:new Object[]{"",3,true}) {
            JSONArray bad=steps("bad",2,due);bad.getJSONObject(0).put("plan_group",invalid);
            try{batch(bad,NOW,600,1320);throw new AssertionError("invalid planning group accepted");}
            catch(ChatCompletionClient.ResponseException expected){checks++;}
        }
        JSONArray missing=steps("missing",2,due);missing.getJSONObject(0).remove("plan_group");
        try{batch(missing,NOW,600,1320);throw new AssertionError("missing plan field accepted");}
        catch(ChatCompletionClient.ResponseException expected){checks++;}
        for(Object invalid:new Object[]{"later",time("2026-02-30","10:00"),new JSONObject().put("time","broken")}) {
            JSONArray bad=steps("bad-time",2,due);bad.getJSONObject(0).put("plan_until",invalid);
            try{batch(bad,NOW,600,1320);throw new AssertionError("invalid boundary silently fell back to final-days scheduling");}
            catch(ChatCompletionClient.ResponseException expected){checks++;}
        }
    }

    private static JSONArray steps(String group,int count,long due)throws Exception {
        ZonedDateTime local=Instant.ofEpochMilli(due).atZone(ZoneId.of("Asia/Shanghai"));
        JSONArray result=new JSONArray();
        for(int i=0;i<count;i++)result.put(base("homework",local.toLocalDate().toString(),local.toLocalTime().toString())
                .put("title","子项"+(i+1)).put("plan_group",group).put("plan_until",clock(due)));
        return result;
    }
    private static JSONObject clock(long instant)throws Exception {
        ZonedDateTime local=Instant.ofEpochMilli(instant).atZone(ZoneId.of("Asia/Shanghai"));
        return time(local.toLocalDate().toString(),local.toLocalTime().toString());
    }
    private static List<EventCandidate> batch(JSONArray events,long now,int start,int end)throws Exception {
        JSONArray model = new JSONArray(events.toString());
        for (int i=0;i<model.length();i++) TimeAssessmentCheck.evidence(model.getJSONObject(i));
        JSONObject content=new JSONObject().put("events",model);
        JSONObject envelope=new JSONObject().put("choices",new JSONArray().put(new JSONObject()
                .put("message",new JSONObject().put("content",content.toString()))));
        return ChatCompletionClient.parseResponse(7,envelope.toString(),NOW,"Asia/Shanghai",now,start,end).candidates;
    }

    private static EventCandidate parse(JSONObject event, long schedulingNow, int start, int end) throws Exception {
        return SemanticEventNormalizer.fromJson(7, event, NOW, "Asia/Shanghai", schedulingNow, start, end);
    }
    private static JSONObject base(String category, String date, String clock) throws Exception {
        return new JSONObject().put("title", "完成报告").put("category", category).put("all_day", false)
                .put("needs_confirmation", false).put("uncertainty_level", 0).put("time_zone_id", "Asia/Shanghai")
                .put("start", JSONObject.NULL).put("end", JSONObject.NULL)
                .put("due", date == null ? JSONObject.NULL : time(date, clock))
                .put("suggested_start", JSONObject.NULL).put("execution_time_explicit", false)
                .put("plan_group",JSONObject.NULL).put("plan_until",JSONObject.NULL)
                .put("duration_minutes", JSONObject.NULL).put("location", JSONObject.NULL).put("description", "原始要求")
                .put("reminder_minutes_before", JSONObject.NULL).put("reminder_specified", false).put("recurrence", JSONObject.NULL);
    }
    private static JSONObject time(String date, String clock) throws Exception {
        return new JSONObject().put("date", date).put("time", clock);
    }
    private static long at(String value) { return Instant.parse(value).toEpochMilli(); }
    private static void check(boolean condition, String label) {
        if (!condition) throw new AssertionError(label);
        checks++;
    }
}
