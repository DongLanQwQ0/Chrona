package com.donglan.chrona.ai;

import com.donglan.chrona.data.EventCandidate;
import org.json.JSONArray;
import org.json.JSONObject;
import java.time.Instant;

/** Real response conversion; fabricated model responses test contracts, not model accuracy. */
public final class TimeAssessmentCheck {
    private static int checks;
    private static final long NOW = at("2026-10-23T02:00:00Z");
    static JSONObject reason(String certainty, String basis, String rule, String reason) throws Exception {
        return new JSONObject().put("certainty", certainty).put("basis", basis)
                .put("rule", rule == null ? JSONObject.NULL : rule).put("reason", reason);
    }
    static JSONObject evidence(JSONObject event) throws Exception {
        JSONObject result = new JSONObject();
        for (String field : TimeAssessment.FIELDS) result.put(field, event.isNull(field) ? JSONObject.NULL
                : reason("explicit", "合成原文中的明确" + field, null, "沿用合成原文"));
        event.put("time_assessment", result);
        return event;
    }
    static JSONObject base() throws Exception {
        JSONObject event = new JSONObject().put("title", "提交材料").put("category", "task")
                .put("uncertainty_level", 0).put("needs_confirmation", false).put("time_zone_id", "Asia/Shanghai")
                .put("all_day", false).put("execution_time_explicit", false)
                .put("duration_minutes", JSONObject.NULL).put("reminder_specified", false);
        for (String field : new String[]{"start","end","due","suggested_start","plan_group","plan_until","recurrence","location","description","reminder_minutes_before"})
            event.put(field, JSONObject.NULL);
        return event;
    }
    static JSONObject time(String date, String clock) throws Exception {
        return new JSONObject().put("date", date).put("time", clock == null ? JSONObject.NULL : clock);
    }
    static ParseResult parse(JSONObject event, long now) throws Exception {
        String content = new JSONObject().put("events", new JSONArray().put(event)).toString();
        String envelope = new JSONObject().put("choices", new JSONArray().put(new JSONObject()
                .put("message", new JSONObject().put("content", content)))).toString();
        return ChatCompletionClient.parseResponse(7, envelope, NOW, "Asia/Shanghai", now, 600, 1320);
    }
    static void rejected(JSONObject event, String label) throws Exception {
        try { parse(event, NOW); throw new AssertionError(label); }
        catch (ChatCompletionClient.ResponseException expected) { checks++; }
    }
    public static void main(String[] args) throws Exception {
        JSONObject multiDay=evidence(base().put("category","event").put("execution_time_explicit",true)
                .put("start",time("2026-11-21",null)).put("end",time("2026-11-22",null)));
        ParseResult range=parse(multiDay,NOW);EventCandidate rangeItem=range.candidates.get(0);
        check(rangeItem.startAtMillis==at("2026-11-21T07:00:00Z")&&rangeItem.endAtMillis==at("2026-11-22T08:00:00Z"),"date-only cross-day range preserves both supplied dates instead of collapsing to one hour");
        check(rangeItem.uncertaintyLevel==2&&rangeItem.needsConfirmation&&!rangeItem.endAutoGenerated,"suggested clocks remain doubtful while an explicit end date is retained");
        JSONObject rangeAudit=new JSONObject(range.timeAuditJson).getJSONArray("entries").getJSONObject(0);
        check(rangeAudit.getJSONObject("model").getJSONObject("end").getString("date").equals("2026-11-22")&&rangeAudit.getJSONArray("adjustments").toString().contains("保留该日期"),"cross-day audit preserves source date and explains the clock-only suggestion");
        multiDay.put("start",time("2026-11-21","18:30"));evidence(multiDay);rangeItem=parse(multiDay,NOW).candidates.get(0);
        check(rangeItem.endAtMillis==at("2026-11-22T11:30:00Z"),"missing end clock follows start clock plus duration on the supplied end date");
        multiDay.put("end",time("2026-11-22","11:00"));evidence(multiDay);rangeItem=parse(multiDay,NOW).candidates.get(0);
        check(rangeItem.endAtMillis==at("2026-11-22T03:00:00Z"),"explicit end clock is never replaced by the provisional rule");
        multiDay.put("all_day",true).put("start",time("2026-11-21",null)).put("end",time("2026-11-22",null));evidence(multiDay);rangeItem=parse(multiDay,NOW).candidates.get(0);
        check(rangeItem.allDay&&rangeItem.endAtMillis==at("2026-11-23T00:00:00Z"),"whole-day ranges retain inclusive date conversion");
        multiDay.put("all_day",false).put("end",time("2026-11-20",null));evidence(multiDay);rangeItem=parse(multiDay,NOW).candidates.get(0);
        check(rangeItem.endAtMillis==null&&rangeItem.needsConfirmation,"backwards explicit end date is not silently replaced with a same-day default");
        JSONObject ambiguous=evidence(base().put("category","event").put("execution_time_explicit",true).put("time_zone_id","America/New_York")
                .put("start",time("2026-11-01","00:30")).put("end",time("2026-11-01","01:30")));
        rangeItem=parse(ambiguous,NOW).candidates.get(0);
        check(rangeItem.endAtMillis==null&&rangeItem.needsConfirmation,"explicit ambiguous DST end clock is never replaced by a guessed clock");
        JSONObject dateOnly = evidence(base().put("due", time("2026-11-03", null)));
        dateOnly.getJSONObject("time_assessment").put("due",
                reason("rule_based", "11月3日截止", "date_only_deadline", "日期明确，默认当天23:59截止"));
        ParseResult result = parse(dateOnly, NOW);
        EventCandidate item = result.candidates.get(0);
        check(item.dueAtMillis == at("2026-11-03T15:59:00Z"), "date-only deadline is preserved independently");
        check(item.startAtMillis < at("2026-11-01T00:00:00Z") && item.endAtMillis-item.startAtMillis == 30*60000L,
                "single date-only deadline uses the full preparation period, never a fixed final evening");
        check(item.uncertaintyLevel == 2 && item.needsConfirmation, "freely chosen execution remains doubtful despite a clear due date");
        check(item.endAutoGenerated && item.description.contains("待确认"), "program execution suggestion remains editable");
        JSONObject audit = new JSONObject(result.timeAuditJson);
        JSONObject entry = audit.getJSONArray("entries").getJSONObject(0);
        check(entry.getJSONObject("model").getJSONObject("due").isNull("time"), "audit retains missing original clock");
        check(entry.getJSONObject("resolved").getLong("start") == item.startAtMillis, "audit retains actual normalized instant");
        check(entry.getJSONArray("adjustments").toString().contains("整个可用周期"), "local scheduling recorded separately from model evidence");
        check(audit.getLong("reference_epoch_millis") == NOW && audit.getString("prompt_version").equals(SchedulePrompt.VERSION), "parse context version and time anchor recorded");
        check(entry.getJSONObject("resolved_time_assessment").getJSONObject("due").getString("certainty").equals("rule_based")
                && entry.getJSONObject("resolved_time_assessment").getJSONObject("start").getString("certainty").equals("uncertain"),
                "clear due and free execution have independent final certainty");
        JSONObject clockOnly = evidence(base().put("category","event").put("execution_time_explicit",true)
                .put("start",new JSONObject().put("time","16:00")));
        JSONObject clockAudit = new JSONObject(parse(clockOnly,NOW).timeAuditJson).getJSONArray("entries").getJSONObject(0);
        check(clockAudit.getJSONObject("resolved_time_assessment").getJSONObject("start").getString("certainty").equals("uncertain")
                && clockAudit.getJSONObject("resolved_time_assessment").getJSONObject("start").getString("reason").contains("最近一次日期"),
                "local missing-date inference cannot retain false model explicit certainty");
        clockOnly.put("end", new JSONObject().put("time","17:00")); evidence(clockOnly);
        JSONObject inherited = new JSONObject(parse(clockOnly,NOW).timeAuditJson).getJSONArray("entries").getJSONObject(0);
        check(inherited.getJSONObject("resolved_time_assessment").getJSONObject("end").getString("certainty").equals("uncertain")
                && inherited.getJSONObject("resolved_time_assessment").getJSONObject("end").getString("reason").contains("继承"),
                "end inherits date uncertainty when the source start date was inferred");
        JSONObject knownDate = evidence(base().put("category","event").put("execution_time_explicit",true)
                .put("start", time("2026-10-24",null)).put("end",new JSONObject().put("time","17:00")));
        JSONObject knownAudit = new JSONObject(parse(knownDate,NOW).timeAuditJson).getJSONArray("entries").getJSONObject(0);
        check(knownAudit.getJSONObject("resolved_time_assessment").getJSONObject("end").getString("certainty").equals("explicit"),
                "only clock uncertainty never contaminates a known inherited date");
        JSONObject paddedZone = evidence(base().put("category","event").put("execution_time_explicit",true)
                .put("start",time("2026-10-24","09:00")).put("time_zone_id"," Asia/Shanghai "));
        JSONObject paddedAudit = new JSONObject(parse(paddedZone,NOW).timeAuditJson).getJSONArray("entries").getJSONObject(0);
        check(!paddedAudit.getJSONObject("source_time_validation").getJSONObject("start").getBoolean("requires_review"),
                "audit uses the same normalized timezone as the actual converter");
        JSONObject conflict = evidence(base().put("category","event").put("execution_time_explicit",true)
                .put("start",time("2026-10-25","16:00").put("day_offset",1)));
        JSONObject conflictAudit = new JSONObject(parse(conflict,NOW).timeAuditJson).getJSONArray("entries").getJSONObject(0);
        check(conflictAudit.getJSONObject("resolved_time_assessment").getJSONObject("start").getString("certainty").equals("uncertain")
                && conflictAudit.getJSONObject("source_time_validation").getJSONObject("start").getJSONArray("notes").toString().contains("冲突"),
                "local conflicting anchors are recorded without rewriting the source evidence");

        JSONObject fuzzy = evidence(base().put("due", time("2026-11-03", null)));
        fuzzy.getJSONObject("time_assessment").put("due", reason("uncertain", "3号截止", null, "月份未明确，暂用11月"));
        item = parse(fuzzy, NOW).candidates.get(0);
        check(item.startAtMillis != null && item.uncertaintyLevel == 2 && item.needsConfirmation,
                "time evidence forces uncertainty even if model incorrectly labels the whole item certain");
        check(parse(evidence(base().put("due", time("2026-11-03", "18:00"))), NOW).candidates.get(0).uncertaintyLevel == 2,
                "explicit deadline is not the same as certain execution");
        JSONObject fixed = evidence(base().put("due", time("2026-11-03", null))
                .put("start", time("2026-10-25", "09:00")).put("execution_time_explicit", true));
        check(parse(fixed, NOW).candidates.get(0).startAtMillis == at("2026-10-25T01:00:00Z"), "explicit source execution is never replaced by automatic placement");
        item = parse(dateOnly, at("2026-11-03T14:30:00Z")).candidates.get(0);
        check(item.uncertaintyLevel == 2 && item.startAtMillis == null && item.dueAtMillis != null,
                "exhausted work window cannot fabricate an impossible execution interval");

        JSONObject custom = evidence(base().put("due", time("2026-11-03", null))
                .put("suggested_start", time("2026-11-02", "20:00")).put("duration_minutes", 90));
        custom.getJSONObject("time_assessment").put("suggested_start",
                reason("rule_based", "已保存偏好：截止前一天20点开始，执行90分钟", "截止前一天20点开始，执行90分钟", "唯一匹配该偏好"));
        item = parse(custom, NOW).candidates.get(0);
        check(item.startAtMillis == at("2026-11-02T12:00:00Z") && item.endAtMillis-item.startAtMillis == 90*60000L
                && item.uncertaintyLevel == 0, "explicit saved preference overrides ordinary placement without inflating uncertainty");
        custom.put("suggested_start", time("2026-11-04", "20:00"));
        item = parse(custom, NOW).candidates.get(0);
        check(item.needsConfirmation && item.endAtMillis <= item.dueAtMillis, "invalid preference stays editable and cannot exceed due");

        JSONObject group = evidence(base().put("due", time("2026-12-03", null)).put("plan_group", "写作")
                .put("plan_until", time("2026-12-03", null)).put("duration_minutes", 180));
        item = parse(group, NOW).candidates.get(0);
        check(item.startAtMillis < at("2026-12-01T00:00:00Z") && item.needsConfirmation, "large grouped work uses the preparation horizon");
        JSONObject noClock = evidence(base().put("category", "event").put("execution_time_explicit", true)
                .put("start", time("2026-10-24", null)));
        item = parse(noClock, NOW).candidates.get(0);
        check(item.startAtMillis != null && item.endAtMillis != null && item.needsConfirmation, "date-only activity gets an editable concrete time rather than empty input");
        check(parse(evidence(base()), NOW).candidates.get(0).startAtMillis == null, "no scheduling intent stays unscheduled");

        rejected(base().put("due", time("2026-11-03", null)), "missing audit must fail");
        JSONObject malformed = new JSONObject(dateOnly.toString());
        malformed.getJSONObject("time_assessment").getJSONObject("due").put("reason", "");
        rejected(malformed, "empty certain reason must fail");
        malformed = new JSONObject(dateOnly.toString());
        malformed.getJSONObject("time_assessment").getJSONObject("due").put("rule", JSONObject.NULL);
        rejected(malformed, "rule-based evidence must name its rule");
        malformed = new JSONObject(dateOnly.toString());
        malformed.getJSONObject("time_assessment").put("due", JSONObject.NULL);
        rejected(malformed, "present time cannot omit evidence");
        malformed = new JSONObject(dateOnly.toString());
        malformed.getJSONObject("time_assessment").getJSONObject("due").put("certainty", "probably");
        rejected(malformed, "unknown certainty must fail");
        malformed = new JSONObject(dateOnly.toString());
        malformed.getJSONObject("time_assessment").getJSONObject("due").put("basis", 42);
        rejected(malformed, "evidence must preserve its string type");
        check(!SchedulePrompt.SYSTEM.contains("deadline_day_evening") && !SchedulePrompt.SYSTEM.contains("22:00–23:00"), "withdrawn deadline-evening preference is absent");
        for (String term : new String[]{"主动排程", "不得仅写", "首阶段尽早启动", "反馈与返工", "不能只给最后一次活动"})
            check(SchedulePrompt.DECISION_RULES.contains(term), "planning obligation: " + term);
        System.out.println("Time assessment: " + checks + " checks passed; actual conversion and response validation, synthetic model outputs");
    }
    static long at(String value) { return Instant.parse(value).toEpochMilli(); }
    static void check(boolean value, String label) { checks++; if (!value) throw new AssertionError(label); }
}
