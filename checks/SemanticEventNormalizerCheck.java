import com.donglan.chrona.ai.SemanticEventNormalizer;
import com.donglan.chrona.data.CandidateRules;
import com.donglan.chrona.data.EventCandidate;
import org.json.JSONObject;
import java.time.Instant;
import java.util.Arrays;
import java.util.List;

/** Offline checks; run with a desktop org.json implementation rather than android.jar stubs. */
public final class SemanticEventNormalizerCheck {
    private static final long NOW = Instant.parse("2026-09-28T02:00:00Z").toEpochMilli();
    private static int checks;

    public static void main(String[] args) throws Exception {
        exclusiveDateDeadlines();
        EventCandidate task = parse(base("task").put("start", time(null, "11:00", 1)));
        check(task.startAtMillis == at("2026-09-29T03:00:00Z"), "relative local date");
        check(task.endAtMillis==null, "task does not invent duration");
        check(!task.needsConfirmation, "complete relative time");
        check(!task.endAutoGenerated, "task has no fabricated end");
        EventCandidate inferred = parse(base("task").put("uncertainty_level", 1)
                .put("needs_confirmation", true).put("start", time(null, "11:00", 1)));
        check(inferred.startAtMillis != null && inferred.needsConfirmation && inferred.uncertaintyLevel == 1,
                "supported inference keeps time and level 1");
        check(parse(base("task").put("uncertainty_level", 0)
                .put("start", time(null, "11:00", 1))).uncertaintyLevel == 0, "explicit level 0");
        check(parse(base("task").put("uncertainty_level", 1)).uncertaintyLevel == 1,
                "unscheduled task keeps model certainty");
        check(parse(base("task").put("uncertainty_level", 7)
                .put("start", time(null, "11:00", 1))).uncertaintyLevel == 2, "invalid level escalates");
        EventCandidate midnightDeadline = parse(base("task").put("due", time("2026-10-05", "24:00", null)));
        check(midnightDeadline.dueAtMillis == at("2026-10-05T15:59:00Z")
                && midnightDeadline.startAtMillis == null,
                "24:00 deadline stays on stated day at 23:59");
        check(parse(base("task").put("due", time("2026-10-05", "24:00:00", null)))
                .dueAtMillis.equals(midnightDeadline.dueAtMillis), "24:00:00 convention");
        check(parse(base("task").put("due", time("2026-10-05", "24:01", null))).dueAtMillis == null,
                "24:01 remains invalid");
        EventCandidate inferredIncomplete = new EventCandidate(0, 7, "推定事项", NOW, null,
                "Asia/Shanghai", null, null, null, true, null, "task", false, true, 1);
        check(com.donglan.chrona.data.EventTimeDefaults.completeInterval(inferredIncomplete).uncertaintyLevel == 1,
                "default interval preserves inferred level");
        EventCandidate relativeInterval = parse(base("event")
                .put("start", new JSONObject().put("offset_minutes", 60))
                .put("end", new JSONObject().put("offset_minutes", 90)));
        check(relativeInterval.startAtMillis == NOW + 60 * 60_000L
                && relativeInterval.endAtMillis == NOW + 90 * 60_000L
                && !relativeInterval.needsConfirmation, "relative end uses instant rather than inherited date");
        EventCandidate activityDefault=parse(base("event").put("start",time("2026-09-29","11:00",null)));
        check(activityDefault.endAtMillis-activityDefault.startAtMillis==60*60_000L,"activity default duration");
        EventCandidate explicit = parse(base("event").put("start", time("2026-09-29", "11:00", null))
                .put("duration_minutes", 90));
        check(explicit.endAtMillis - explicit.startAtMillis == 90 * 60_000L, "explicit duration");
        check(!explicit.endAutoGenerated, "AI duration is protected");
        EventCandidate durationMismatch = parse(base("event").put("start", time("2026-09-29", "11:00", null))
                .put("end", time("2026-09-29", "12:00", null)).put("duration_minutes", 90));
        check(durationMismatch.needsConfirmation && durationMismatch.endAtMillis - durationMismatch.startAtMillis == 60 * 60_000L,
                "explicit end survives contradictory duration");
        check(!durationMismatch.endAutoGenerated, "AI end is protected");
        check(parse(base("event").put("start", time("2026-09-29", "11:00", null))
                .put("duration_minutes", 0)).endAtMillis == null, "invalid duration has no default interval");
        EventCandidate leapDay = parse(base("event").put("start", time("2028-02-29", "11:00", null)));
        check(leapDay.startAtMillis == at("2028-02-29T03:00:00Z"), "valid leap date");
        check(parse(base("event").put("start", time("2026-02-30", "11:00", null))).startAtMillis == null,
                "invalid calendar date");
        EventCandidate missing = parse(base("event").put("start", time(null, "11:00", null)));
        check(missing.startAtMillis == at("2026-09-28T03:00:00Z") && missing.uncertaintyLevel == 2
                && missing.needsConfirmation, "clock without date keeps a concrete doubtful draft");
        check(parse(base("task").put("start", time(null, "09:00", null))).startAtMillis
                == at("2026-09-29T01:00:00Z"), "elapsed clock without date uses next occurrence");
        check(parse(base("task").put("start", time("2026-09-28", "09:00", null))).startAtMillis
                == at("2026-09-28T01:00:00Z"), "explicit elapsed date never silently rolls forward");
        EventCandidate dateOnly = parse(base("event").put("start", time("2026-09-29", null, null)));
        check(dateOnly.startAtMillis == at("2026-09-29T07:00:00Z") && dateOnly.needsConfirmation,
                "date without clock keeps a concrete editable high-uncertainty suggestion");
        EventCandidate contradictory = parse(base("task").put("start", time("2026-09-30", "11:00", 1)));
        check(contradictory.startAtMillis == at("2026-09-30T03:00:00Z") && contradictory.needsConfirmation,
                "explicit date has priority but contradiction requires confirmation");
        JSONObject monday = time(null, "11:00", null).put("weekday", 1).put("week_offset", 1);
        check(parse(base("event").put("start", monday)).startAtMillis == at("2026-10-05T03:00:00Z"), "next week weekday");
        JSONObject passedMonday = time(null, "09:00", null).put("weekday", 1);
        check(parse(base("event").put("start", passedMonday)).startAtMillis == at("2026-10-05T01:00:00Z"),
                "next weekday after elapsed clock");
        JSONObject offset = new JSONObject().put("offset_minutes", 20);
        check(parse(base("task").put("start", offset)).startAtMillis == NOW + 20 * 60_000L, "instant offset");
        EventCandidate sameDateEnd = parse(base("event").put("start", time("2026-09-29", "11:00", null))
                .put("end", time(null, "12:00", null)));
        check(sameDateEnd.endAtMillis == at("2026-09-29T04:00:00Z"), "end inherits start date");
        EventCandidate negative = parse(base("event").put("start", time("2026-09-28", "23:00", null))
                .put("end", time(null, "01:00", null)));
        check(negative.endAtMillis == null && negative.needsConfirmation, "negative interval never guesses overnight");
        EventCandidate overnight = parse(base("event").put("start", time("2026-09-28", "23:00", null))
                .put("end", time(null, "01:00", 1)));
        check(overnight.endAtMillis - overnight.startAtMillis == 2 * 60 * 60_000L, "explicit overnight day offset");
        EventCandidate allDay = parse(base("event").put("all_day", true)
                .put("start", time("2026-09-29", null, null)).put("end", time("2026-09-30", null, null)));
        check(allDay.startAtMillis == at("2026-09-29T00:00:00Z")
                && allDay.endAtMillis == at("2026-10-01T00:00:00Z") && "UTC".equals(allDay.timeZoneId),
                "inclusive all-day dates become exclusive UTC boundary");
        EventCandidate due = parse(base("task").put("due", time("2026-09-28", "10:30", null)));
        EventCandidate homework = parse(base("homework").put("due", time("2026-09-28", "10:30", null)));
        check(homework.isHomework() && homework.isTask() && homework.dueAtMillis != null
                && homework.startAtMillis == null, "homework retains its category and task deadline behavior");
        check("task".equals(due.category)&&due.dueAtMillis!=null&&due.startAtMillis==null&&due.endAtMillis==null,"deadline is task property, not an execution slot");
        check(due.reminderMinutesBefore == 10 && !due.title.contains("2026-09-28 10:30"), "urgent deadline reminder and title");
        check(parse(base("task").put("due", time("2026-09-28", "20:00", null))).reminderMinutesBefore == 30,
                "same-day deadline reminder");
        check(parse(base("task").put("due", time("2026-09-30", "10:00", null))).reminderMinutesBefore == 120,
                "near deadline reminder");
        check(parse(base("task").put("due", time("2026-10-10", "10:00", null))).reminderMinutesBefore == 360,
                "distant deadline reminder");
        JSONObject noReminder = base("task").put("due", time("2026-09-28", "10:30", null))
                .put("reminder_specified", true).put("reminder_minutes_before", JSONObject.NULL);
        check(parse(noReminder).reminderMinutesBefore == null, "explicit no reminder");
        check(parse(noReminder.put("reminder_minutes_before", 0)).reminderMinutesBefore == 0, "explicit zero reminder");
        EventCandidate invalidZone = parse(base("task").put("time_zone_id", "Mars/Olympus")
                .put("start_at_millis", NOW));
        check(invalidZone.startAtMillis == null && invalidZone.needsConfirmation, "invalid timezone");
        check(parse(base("event").put("start_at_millis", Long.MAX_VALUE)).startAtMillis == null, "epoch range");
        check(parse(base("event").put("start", time("2026-09-29", "11:00", null))
                .put("duration_minutes", Long.MAX_VALUE)).endAtMillis == null, "duration overflow");
        for (String[] dst : new String[][]{{"2026-03-08", "02:30"}, {"2026-11-01", "01:30"}}) {
            EventCandidate ambiguous = parse(base("event").put("time_zone_id", "America/New_York")
                    .put("start", time(dst[0], dst[1], null)));
            check(ambiguous.startAtMillis == null && ambiguous.needsConfirmation, "DST gap or overlap");
        }
        check(CandidateRules.apply(Arrays.asList(task, task)).size() == 1, "identical draft deduplicated");
        EventCandidate differentLocation = copy(task, "另一地点", task.reminderMinutesBefore, task.category);
        check(CandidateRules.apply(Arrays.asList(task, differentLocation)).size() == 2, "location difference preserved");
        EventCandidate differentReminder = copy(task, task.location, 15, task.category);
        check(CandidateRules.apply(Arrays.asList(task, differentReminder)).size() == 2, "reminder difference preserved");
        List<EventCandidate> simultaneousTasks = CandidateRules.apply(Arrays.asList(task, differentLocation));
        check(!simultaneousTasks.get(0).needsConfirmation && !simultaneousTasks.get(1).needsConfirmation,
                "simultaneous tasks are not merged or marked as appointment conflict");
        List<EventCandidate> appointments = CandidateRules.apply(Arrays.asList(copy(task, "A", null, "event"),
                copy(task, "B", null, "event")));
        check(appointments.size() == 2 && !appointments.get(0).needsConfirmation && !appointments.get(1).needsConfirmation,
                "explicit appointment overlap preserves certainty");
        EventCandidate inferredAppointment = parse(base("event").put("uncertainty_level", 1)
                .put("needs_confirmation", true).put("start", time(null, "11:00", 1)));
        check(CandidateRules.apply(Arrays.asList(inferredAppointment, copy(inferredAppointment, "B", null, "event")))
                .get(0).uncertaintyLevel == 1, "overlap does not change model uncertainty");
        JSONObject missingLevel = base("task").put("start", time(null, "11:00", 1)); missingLevel.remove("uncertainty_level");
        check(parse(missingLevel).needsConfirmation && parse(missingLevel).uncertaintyLevel == 2, "missing certainty cannot auto-confirm");
        EventCandidate fuzzy = parse(base("task").put("uncertainty_level", 2).put("needs_confirmation", true)
                .put("start", time(null, "19:00", 1)));
        check(fuzzy.startAtMillis != null && fuzzy.needsConfirmation && fuzzy.uncertaintyLevel == 2, "chosen fuzzy time retained for review");
        EventCandidate atSix = parse(base("task").put("uncertainty_level", 2).put("needs_confirmation", true)
                .put("start", time(null, "18:00", 0)).put("reminder_specified", true)
                .put("reminder_minutes_before", 0));
        check(atSix.startAtMillis == at("2026-09-28T10:00:00Z") && atSix.dueAtMillis == null
                && atSix.endAtMillis == null && atSix.reminderMinutesBefore == 0 && atSix.needsConfirmation,
                "at-time reminder is scheduled task, not invented deadline or duration");
        // These are model-output contract fixtures, not claims of live-model interpretation accuracy.
        for (String[] example : new String[][] {
                {"2026-10-15T01:00:00+08:00", "0", "09:00", "2026-10-15T01:00:00Z"},
                {"2026-10-15T13:00:00+08:00", "0", "14:00", "2026-10-15T06:00:00Z"},
                {"2026-10-15T15:00:00+08:00", "1", "14:00", "2026-10-16T06:00:00Z"},
                {"2026-10-15T23:00:00+08:00", "1", "01:00", "2026-10-15T17:00:00Z"}
        }) {
            EventCandidate draft = SemanticEventNormalizer.fromJson(7, base("task")
                    .put("uncertainty_level", 2).put("needs_confirmation", true)
                    .put("start", time(null, example[2], Integer.valueOf(example[1]))),
                    at(example[0]), "Asia/Shanghai");
            check(draft.startAtMillis == at(example[3]) && draft.uncertaintyLevel == 2
                    && draft.needsConfirmation, "colloquial model choice retained: " + Arrays.toString(example));
        }
        System.out.println("SemanticEventNormalizerCheck passed: " + checks + " checks");
    }

    private static void exclusiveDateDeadlines() throws Exception {
        for (String[] boundary : new String[][] {
                {"2026-11-03", "2026-11-02T15:59:00Z"},
                {"2026-11-01", "2026-10-31T15:59:00Z"},
                {"2027-01-01", "2026-12-31T15:59:00Z"},
                {"2028-03-01", "2028-02-29T15:59:00Z"},
                {"2027-03-01", "2027-02-28T15:59:00Z"}
        }) {
            JSONObject source = base("task").put("due", exclusive(time(boundary[0], null, null)));
            String original = source.toString();
            EventCandidate item = parse(source);
            check(item.dueAtMillis != null && item.dueAtMillis == at(boundary[1])
                    && !item.needsConfirmation && item.uncertaintyLevel == 0,
                    "exclusive date resolves once, with no added uncertainty: " + boundary[0]);
            check(source.toString().equals(original), "exclusive normalization preserves raw date and marker");
        }
        check(parse(base("homework").put("due", exclusive(time(null, null, 1)))).dueAtMillis
                == at("2026-09-28T15:59:00Z"), "relative day deadline excludes the anchored date");
        check(parse(base("task").put("due", exclusive(time(null, null, null)
                .put("weekday", 1).put("week_offset", 1)))).dueAtMillis
                == at("2026-10-04T15:59:00Z"), "next-week weekday deadline excludes the selected Monday");
        check(parse(base("task").put("due", exclusive(time(null, null, null).put("weekday", 2)))).dueAtMillis
                == at("2026-09-28T15:59:00Z"), "bare weekday anchors before subtracting a calendar date");
        check(parse(base("task").put("due", exclusive(time(null, null, null).put("weekday", 1)))).dueAtMillis
                == at("2026-09-27T15:59:00Z"), "current weekday exclusive boundary does not silently advance a week");
        EventCandidate dst = parse(base("task").put("time_zone_id", "America/New_York")
                .put("due", exclusive(time("2026-11-02", null, null))));
        check(dst.dueAtMillis == at("2026-11-02T04:59:00Z"),
                "exclusive deadline subtracts a local calendar day across DST, not 24 hours");
        check(parse(base("task").put("due", time("2026-11-03", null, null)
                .put("date_exclusive", false))).dueAtMillis == at("2026-11-03T15:59:00Z"),
                "inclusive stated-date deadline remains on the stated day");
        JSONObject legacy = time("2026-11-03", null, null);
        legacy.remove("date_exclusive");
        check(parse(base("task").put("due", legacy)).dueAtMillis == at("2026-11-03T15:59:00Z"),
                "direct normalizer missing-marker contract remains inclusive");
        check(parse(base("task").put("due", time("2026-11-03", "18:00", null)
                .put("date_exclusive", false))).dueAtMillis == at("2026-11-03T10:00:00Z"),
                "clock-level before semantics keep the exact clock on the stated date");
        for (JSONObject invalid : new JSONObject[] {
                exclusive(time("2026-11-03", "18:00", null)),
                exclusive(new JSONObject().put("offset_minutes", 60)),
                exclusive(new JSONObject())
        }) {
            EventCandidate item = parse(base("task").put("due", invalid));
            check(item.dueAtMillis == null && item.needsConfirmation && item.uncertaintyLevel == 2,
                    "invalid exclusive due stays unresolved in direct normalizer: " + invalid);
        }
        for (String field : new String[]{"start", "end", "suggested_start"}) {
            EventCandidate item = parse(base("task").put(field, exclusive(time("2026-11-03", null, null))));
            check(item.startAtMillis == null && item.endAtMillis == null && item.needsConfirmation
                    && item.uncertaintyLevel == 2, "exclusive marker forbidden for direct " + field);
        }
        EventCandidate allDay = parse(base("task").put("all_day", true)
                .put("due", exclusive(time("2026-11-03", null, null))));
        check(allDay.dueAtMillis == at("2026-11-02T15:59:00Z") && !allDay.allDay,
                "all-day deadline-only task retains the previous local end of day");
        allDay = parse(base("task").put("all_day", true)
                .put("start", time("2026-11-01", null, null))
                .put("end", time("2026-11-01", null, null))
                .put("due", exclusive(time("2026-11-03", null, null))));
        check(allDay.allDay && allDay.startAtMillis == at("2026-11-01T00:00:00Z")
                && allDay.endAtMillis == at("2026-11-02T00:00:00Z")
                && allDay.dueAtMillis == at("2026-11-02T15:59:00Z"),
                "all-day execution encoding never subtracts a second day from due or execution dates");
        EventCandidate reminder = parse(base("task").put("due", exclusive(time(null, null, 1))));
        check(reminder.reminderMinutesBefore == 30 && reminder.reminderAnchor().equals(reminder.dueAtMillis),
                "default reminder uses the adjusted same-day deadline and anchor");
        reminder = parse(base("task").put("due", exclusive(time(null, null, 1)))
                .put("reminder_specified", true).put("reminder_minutes_before", 15));
        check(reminder.reminderMinutesBefore == 15 && reminder.reminderAnchor().equals(reminder.dueAtMillis),
                "explicit reminder stays unchanged while its deadline anchor moves once");
    }

    private static JSONObject exclusive(JSONObject time) throws Exception {
        return time.put("date_exclusive", true);
    }

    private static JSONObject base(String category) throws Exception {
        return new JSONObject().put("title", "事项").put("category", category).put("needs_confirmation", false).put("uncertainty_level", 0)
                .put("time_zone_id", JSONObject.NULL).put("all_day", false);
    }

    private static JSONObject time(String date, String clock, Integer day) throws Exception {
        return new JSONObject().put("date", date == null ? JSONObject.NULL : date)
                .put("time", clock == null ? JSONObject.NULL : clock).put("day_offset", day == null ? JSONObject.NULL : day);
    }

    private static EventCandidate parse(JSONObject object) throws Exception {
        return SemanticEventNormalizer.fromJson(7, object, NOW, "Asia/Shanghai");
    }

    private static EventCandidate copy(EventCandidate value, String location, Integer reminder, String category) {
        return new EventCandidate(0, value.taskId, value.title, value.startAtMillis, value.endAtMillis,
                value.timeZoneId, location, value.description, reminder, false, null, category, value.allDay);
    }

    private static long at(String instant) { return Instant.parse(instant).toEpochMilli(); }
    private static void check(boolean value, String label) {
        checks++;
        if (!value) throw new AssertionError(label);
    }
}
